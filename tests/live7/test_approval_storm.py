# ---- B. identical calls ---------------------------------------------------------------------- #

def test_identical_call_while_waiting_does_not_ask_again():
    gate = {}

    async def answer(intent):
        gate.setdefault("f", asyncio.get_running_loop().create_future())
        return await gate["f"]

    async def go():
        bridge, ran, asked, audit = make(answer)
        first = asyncio.create_task(bridge.dispatch("app_open", {"name": "chrome", "dry_run": False}))
        await asyncio.sleep(0.05)
        dups = [await bridge.dispatch("app_open", {"dry_run": False, "name": "chrome"}) for _ in range(5)]
        gate["f"].set_result(True)
        r1 = await first
        return r1, dups, ran, asked, audit

    r1, dups, ran, asked, audit = asyncio.run(go())
    assert len(asked) == 1 and len(ran) == 1 and r1["ok"] is True
    for d in dups:
        assert d["ok"] is False and d.get("duplicate") is True and "already waiting" in d["error"]
    assert any(e.startswith("live_tool_") and e not in ("live_tool_policy", "live_tool_approval",
               "live_tool_result") for e in events(audit))


def test_after_yes_the_same_call_is_not_asked_or_run_again():
    clock = Clock()

    async def go():
        bridge, ran, asked, audit = make(clock=clock)
        a = await bridge.dispatch("app_open", {"name": "chrome"})
        clock.t += 5
        b = await bridge.dispatch("app_open", {"name": "chrome"})
        clock.t += 61
        c = await bridge.dispatch("app_open", {"name": "chrome"})
        return a, b, c, ran, asked

    a, b, c, ran, asked = asyncio.run(go())
    assert a["ok"] is True and b["ok"] is True and b.get("duplicate") is True
    assert b["result"] == a["result"]
    assert len(asked) == 2 and len(ran) == 2          # 2nd skipped, 3rd (after the window) asks again


def test_after_no_the_same_call_is_refused_without_asking():
    clock = Clock()

    async def no(intent):
        return False

    async def go():
        bridge, ran, asked, audit = make(no, clock=clock)
        a = await bridge.dispatch("app_open", {"name": "chrome"})
        clock.t += 3
        b = await bridge.dispatch("app_open", {"name": "chrome"})
        other = await bridge.dispatch("app_open", {"name": "safari"})
        clock.t += 61
        c = await bridge.dispatch("app_open", {"name": "chrome"})
        return a, b, other, c, ran, asked

    a, b, other, c, ran, asked = asyncio.run(go())
    assert a["ok"] is False and b["ok"] is False and b.get("approved") is False
    assert "said no" in b["error"] and "do not retry" in b["error"]
    assert ran == [] and asked == [{"name": "chrome"}, {"name": "safari"}, {"name": "chrome"}]


def test_too_many_approval_requests_are_refused():
    clock = Clock()

    async def go():
        bridge, ran, asked, audit = make(clock=clock, max_gated_calls=3, gated_window_s=10.0)
        out = [await bridge.dispatch("app_open", {"name": f"app{i}"}) for i in range(5)]
        clock.t += 11
        later = await bridge.dispatch("app_open", {"name": "app9"})
        return out, later, asked

    out, later, asked = asyncio.run(go())
    assert [o["ok"] for o in out] == [True, True, True, False, False]
    assert "too many" in out[3]["error"]
    assert len(asked) == 4 and later["ok"] is True


def test_low_risk_tools_unaffected():
    async def go():
        bridge, ran, asked, audit = make()
        return [await bridge.dispatch("weather_report", {"city": "Ludhiana"}) for _ in range(12)], ran

    out, ran = asyncio.run(go())
    assert all(o["ok"] is True and not o.get("duplicate") for o in out) and len(ran) == 12


