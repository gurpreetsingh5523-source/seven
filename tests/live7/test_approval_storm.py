def test_one_utterance_settles_one_approval():
    async def send(e):
        pass

    async def go():
        ap = VoiceApprovals(send, announce=None, timeout_s=0.6)
        intents = [ActionIntent(tool="app_open", payload={"name": f"a{i}"}, risk=RiskLevel.HIGH,
                                capabilities=Capability.EXTERNAL_EFFECT) for i in range(3)]
        tasks = [asyncio.create_task(ap.callback(i, None)) for i in intents]
        await asyncio.sleep(0.05)
        for frag in ("haan", " haan", "ji haan"):        # one spoken answer, three fragments
            ap.on_user_transcript(frag)
        await asyncio.sleep(0.05)
        ap.end_utterance()
        ap.on_user_transcript("haan")                     # a new utterance may settle the next one
        return await asyncio.gather(*tasks)

    assert asyncio.run(go()) == [True, True, False]


def test_relay_ends_utterance_on_turn_complete():
    calls = []

    class AP:
        def on_user_transcript(self, text):
            calls.append(("t", text))
            return False

        def end_utterance(self):
            calls.append("end")

    async def send(e):
        pass

    relay = LiveRelay(None, None, send, approvals=AP())
    asyncio.run(relay.handle_response(types.LiveServerMessage(server_content=types.LiveServerContent(
        input_transcription=types.Transcription(text="haan")))))
    asyncio.run(relay.handle_response(types.LiveServerMessage(server_content=types.LiveServerContent(
        turn_complete=True))))
    assert calls == [("t", "haan"), "end"]


