"""Exam — approval storm (seen live 2026-10-08 07:52-07:55, real audit log).

Hermes: make these pass. Do not edit this file.

What happened: the user asked 7 something, 7 called app_open {"name": "chrome"} (HIGH -> approval card).
In 3 minutes there were 233 app_open calls, 211 approval cards, 20 Chrome opens (the user kept pressing
Yes, then No) and the cards never stopped, even right after a Yes. Two causes:
  1. live7/__main__.py approval_announce() speaks the question by relay.say(question), i.e. it sends a
     USER turn "I want to run app_open (dry_run False, name chrome). Should I go ahead — yes or no?" to
     Gemini. To the model that is the user asking for Chrome -> it calls app_open again -> new card ->
     new user turn -> loop (~2 calls/s).
  2. Nothing in ToolBridge stops identical calls: a call identical to one already waiting, just
     approved, or just refused asks the user again.
Also: Gemini delivers ONE spoken "haan" as several input-transcription fragments; each fragment
resolved another pending card, so one word could approve many actions.

Required:
A. live7.relay.LiveRelay.ask_approval(question: str) -> sends ONE user turn that starts with
   "[Approval]", tells 7 to ask the user that question out loud in one short sentence in the user's
   language, and says not to call any tool (text contains "do not call" case-insensitive). It must not
   start with the bare question. live7/__main__.py approval_announce uses relay.ask_approval (and no
   longer relay.say) for approval questions.
B. live7.tools.ToolBridge(registry, policy, sandbox, audit, approval, *, repeat_window_s=60.0,
   max_gated_calls=8, gated_window_s=10.0, clock=time.monotonic) — the same call = same tool name +
   same args (dict, compare canonically, key order does not matter). For calls that need approval:
   - identical to one still WAITING for approval -> return at once
     {"ok": False, "duplicate": True, "error": "... already waiting for the user's approval ..."}
     without a new approval request;
   - identical to one APPROVED and run within repeat_window_s -> return at once
     {"ok": True, "duplicate": True, "result": <the earlier result>} without asking or running again;
   - identical to one REFUSED or timed out within repeat_window_s -> return at once
     {"ok": False, "approved": False, "error": "... the user said no ... do not retry ..."} without asking;
   - more than max_gated_calls approval requests within gated_window_s -> refuse without asking:
     {"ok": False, "error": "... too many ..."};
   each of these is written to the audit log (event name starts with "live_tool_").
   Different args are a different call and still ask. Low-risk (no approval) tools are unaffected.
C. live7.approvals.VoiceApprovals: one user utterance settles at most ONE pending approval.
   end_utterance() starts a new utterance; LiveRelay calls approvals.end_utterance() whenever a
   server_content has turn_complete (or interrupted).
D. The system prompt in live7/__main__.py tells 7: when an action is not approved, do not retry it,
   ask the user instead (prompt text contains "not approved" and "do not retry", case-insensitive).
"""

import asyncio
