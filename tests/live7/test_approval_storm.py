def test_storm_reproduction_gives_one_card():
    """A fake Gemini that calls app_open chrome after EVERY user turn (what the real one did).
    Approvals announce through relay.ask_approval like __main__ does. One card, not a storm."""
    cards, ran = [], []

    async def app_open(p):
        ran.append(p)
        return {"opened": True}

    reg = ToolRegistry()
    reg.register(ToolSpec("app_open", app_open, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT))

    async def go():
        holder = {}
        n = {"i": 0}

        def model_calls_app_open():
            n["i"] += 1
            msg = types.LiveServerMessage(tool_call=types.LiveServerToolCall(function_calls=[
                types.FunctionCall(id=f"c{n['i']}", name="app_open",
                                   args={"name": "chrome", "dry_run": False})]))
            asyncio.get_running_loop().create_task(holder["relay"].handle_response(msg))

        class S:
            async def send_client_content(self, turns=None, turn_complete=None):
                model_calls_app_open()

            async def send_tool_response(self, function_responses=None):
                model_calls_app_open()                    # the model retries after every answer

        async def send(e):
            if e.get("type") == "approval_needed":
                cards.append(e)

        async def announce(q):
            await holder["relay"].ask_approval(q)

        ap = VoiceApprovals(send, announce=announce, timeout_s=1.0)
        bridge = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                            AuditLog(), ApprovalGate(ap.callback, timeout_s=5))
        holder["relay"] = LiveRelay(S(), bridge, send, approvals=ap)
        model_calls_app_open()
        await asyncio.sleep(0.3)
        ap.resolve(cards[0]["action_id"], True)           # the user presses Yes once
        await asyncio.sleep(1.5)
        for t in asyncio.all_tasks() - {asyncio.current_task()}:
            t.cancel()

    asyncio.run(go())
    assert len(cards) == 1, len(cards)
    assert len(ran) == 1
