from sentinel_orchestrator import (ApprovalGate, AuditLog, LocalSandbox, PolicyEngine,  # noqa: E402
                                   SecretsBroker, ToolRegistry)

JPEG = b"\xff\xd8\xff\xe0" + b"\x00" * 2000 + b"\xff\xd9"


class S:
    def __init__(self):
        self.realtime = []

    async def send_realtime_input(self, **kw):
        assert "media" not in kw
        self.realtime.append(kw)

    async def send_client_content(self, **kw):
        pass

    async def send_tool_response(self, **kw):
        pass

    async def receive(self):
        while True:
            await asyncio.sleep(3600)
            yield None


async def _noop(e):
    pass


def test_video_frame_goes_out_as_video_blob():
    s = S()
    relay = LiveRelay(s, None, _noop)
    assert asyncio.run(relay.handle_video(JPEG)) is True
    blob = s.realtime[0]["video"]
    assert blob.data == JPEG and blob.mime_type == "image/jpeg"


def test_rate_limit_size_and_type():
    s = S()
    relay = LiveRelay(s, None, _noop)

    async def go():
        sent = [await relay.handle_video(JPEG) for _ in range(5)]   # same instant
        big = await relay.handle_video(b"\xff\xd8" + b"\x00" * 1_600_000)
        gif = await relay.handle_video(b"GIF89a", mime="image/gif")
        await asyncio.sleep(1.05)
        later = await relay.handle_video(JPEG)
        return sent, big, gif, later

    sent, big, gif, later = asyncio.run(go())
    assert sent.count(True) == 2           # max 2 per second
    assert big is False and gif is False
    assert later is True


def bridge():
    async def no(i, d):
        return False
    return ToolBridge(ToolRegistry(), PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                      AuditLog(), ApprovalGate(no, timeout_s=1))


def test_server_routes_V_frames_and_respects_off_switch():
    from websockets.asyncio.client import connect
    made = []

    def factory(**kw):
        @contextlib.asynccontextmanager
        async def cm():
            s = S(); made.append(s)
            yield s
        return cm()

    async def go():
        server = await start_server(factory, bridge(), port=0)
        base = f"http://127.0.0.1:{server.port}"
        try:
            async with connect(f"ws://127.0.0.1:{server.port}/live", origin=base) as ws:
                await asyncio.sleep(0.3)
                await ws.send(b"V" + JPEG)                         # sharing is OFF -> dropped
                await ws.send(json.dumps({"type": "vision", "source": "screen"}))
                got = []
                for _ in range(6):
                    try:
                        m = await asyncio.wait_for(ws.recv(), 0.5)
                    except asyncio.TimeoutError:
                        break
                    if isinstance(m, str):
                        got.append(json.loads(m))
                await ws.send(b"V" + JPEG)                         # sharing ON -> forwarded
                await ws.send(b"\x01\x00" * 160)                   # plain mic PCM still works
                await asyncio.sleep(0.4)
                await ws.send(json.dumps({"type": "vision", "source": "off"}))
                await asyncio.sleep(0.2)
                await asyncio.sleep(1.1)
                await ws.send(b"V" + JPEG)                         # OFF again -> dropped
                await asyncio.sleep(0.4)
                return got
        finally:
            await server.close()

    got = asyncio.run(go())
    s = made[0]
    videos = [r for r in s.realtime if "video" in r]
    audios = [r for r in s.realtime if "audio" in r]
    assert {"type": "vision", "source": "screen"} in got
    assert len(videos) == 1 and videos[0]["video"].data == JPEG
    assert audios and audios[0]["audio"].mime_type == "audio/pcm;rate=16000"


