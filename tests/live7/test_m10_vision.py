"""M10 exam — vision: "look at my screen" and camera, sent to Gemini Live as video frames.

Hermes: make these pass. Do not edit this file.

Privacy rules (non-negotiable)
- Frames are sent ONLY while the user has screen or camera sharing switched on in the page;
  the page shows a clear red "sharing screen" / "camera on" badge the whole time.
- The server never stores frames on disk and never forwards them anywhere except the live session.
- Rate limit: at most 2 frames per second per connection; frames over 1.5 MB are rejected.

Required
--------
live7.relay.LiveRelay
    async .handle_video(jpeg: bytes, mime="image/jpeg") -> bool
        sends session.send_realtime_input(video=types.Blob(data=jpeg, mime_type=mime)) and returns True;
        returns False (and sends nothing) if over the rate limit (>2/s, measured with time.monotonic())
        or larger than 1_500_000 bytes or mime not image/jpeg or image/png.
live7.server (WebSocket protocol)
    a binary frame whose first byte is 0x56 ('V') is a video frame: payload = the rest (JPEG);
    every other binary frame is still mic PCM. Client text messages
        {"type":"vision","source":"screen"|"camera"|"off"} -> server replies {"type":"vision","source":...}
    and remembers it; video frames received while source is "off" are dropped (privacy).
static/live.html
    buttons id="share-screen" (getDisplayMedia) and id="share-camera" (getUserMedia video);
    captures to a canvas, JPEG (quality ~0.6, max 1280 px wide) at 1 fps, sends 'V'+jpeg binary frames;
    visible badge id="vision-badge" while sharing; stopping the share (or the browser's stop button)
    sends {"type":"vision","source":"off"}.
"""

