"""M12 exam — work timeline, quiet-moment Hermes announcements, drag-and-drop files.

Hermes: make these pass. Do not edit this file.
User's concern: "7 gives Hermes a job, the answer comes later — by then I'm doing something else."
So: never interrupt; wait for a quiet moment, say a SHORT summary first, keep the full answer
available, and show every job on screen.

Required
--------
live7.relay.LiveRelay(..., clock=time.monotonic, quiet_s=2.5)
    .note_activity()        called internally on input transcription, model audio/transcription,
                            tool calls; marks "now" as busy
    .is_idle() -> bool      True when nothing happened for >= quiet_s and no tool is running
    .announce_hermes(job)   if idle: send immediately; else queue (FIFO). The spoken turn starts with
                            "[Hermes finished]" and carries a summary of at most 300 characters of the
                            reply plus a hint that the full answer is available via hermes_result.
                            Always emits {"type":"hermes_done","job_id","status","summary"} at once.
    async .tick()           if idle and the queue is not empty: send ONE queued announcement.
live7.server: calls relay.tick() about every 0.5 s per connection.
live7.hermes_bridge.HermesBridge(..., on_start=None)
    on_start: async callable(job) awaited when a job starts (status "running").
live7.relay.LiveRelay.job_event(job) -> emits {"type":"job","job_id","task","status","seconds"}
    (server/__main__ wire on_start and on_done to it so the page can show a timeline).
Files: client message {"type":"file","name": str, "mime": str, "data_b64": str}
    live7.files.ingest_file(name, mime, data: bytes, uploads_dir) -> dict
        rejects > 10 MB, sanitises the name (no path separators, no leading dots), saves under
        uploads_dir, returns {"ok", "path", "kind": "image"|"text"|"unsupported", "text"?: str}
        text kinds: .txt .md .csv .json .py (UTF-8) — and .pdf/.docx if pypdf/python-docx import.
    relay.handle_file(msg): image -> send_realtime_input(video=Blob) (explicit user action, allowed
        even when screen sharing is off); text -> one user turn "[User shared file <name>]\n<first
        8000 chars>"; emits {"type":"file_received","name","kind","chars"}; unsupported -> error event.
static/live.html: a jobs panel id="jobs" (running/done/failed with elapsed time, click to read the
    reply) and a drop zone / file picker id="drop" sending the file message (max 10 MB).
"""

