from live7.files import ingest_file  # noqa: E402
from live7.hermes_bridge import HermesBridge  # noqa: E402
from live7.relay import LiveRelay  # noqa: E402


class Clock:
    def __init__(self):
        self.t = 1000.0

    def __call__(self):
        return self.t


class S:
    def __init__(self):
        self.client_content, self.realtime = [], []

    async def send_client_content(self, turns=None, turn_complete=None):
        self.client_content.append(turns)

    async def send_realtime_input(self, **kw):
        self.realtime.append(kw)

    async def send_tool_response(self, **kw):
        pass


def text_of(turns):
    c = turns[0] if isinstance(turns, list) else turns
    return c.parts[0].text


def make(clock):
    s, events = S(), []

    async def ev(e):
        events.append(e)

    return s, events, LiveRelay(s, None, ev, clock=clock, quiet_s=2.5)


JOB = {"id": "j1", "task": "What is 17*23?", "status": "done", "reply": "The answer is 391. " + "x" * 2000}


def test_idle_announces_now_with_short_summary():
    clock = Clock()
    s, events, relay = make(clock)
    asyncio.run(relay.announce_hermes(JOB))
    assert len(s.client_content) == 1
    t = text_of(s.client_content[0])
    assert t.startswith("[Hermes finished]") and "391" in t and "hermes_result" in t
    assert len(t) <= 300 + 250
    done = [e for e in events if e["type"] == "hermes_done"][0]
    assert done["job_id"] == "j1" and len(done["summary"]) <= 300


def test_busy_user_is_not_interrupted_until_quiet():
    clock = Clock()
    s, events, relay = make(clock)

    async def go():
        await relay.handle_response(types.LiveServerMessage(server_content=types.LiveServerContent(
            input_transcription=types.Transcription(text="I'm telling you something long"))))
        await relay.announce_hermes(JOB)
        assert s.client_content == []                       # user is talking: queued
        assert any(e["type"] == "hermes_done" for e in events)   # timeline still updated at once
        clock.t += 1.0
        await relay.tick()
        assert s.client_content == []                       # still within quiet window
        clock.t += 2.0
        assert relay.is_idle()
        await relay.tick()
        assert len(s.client_content) == 1                   # spoken in the quiet moment
        await relay.tick()
        assert len(s.client_content) == 1                   # only once

    asyncio.run(go())


def test_queue_is_fifo_one_per_tick():
    clock = Clock()
    s, events, relay = make(clock)

    async def go():
        relay.note_activity()
        await relay.announce_hermes({**JOB, "id": "a", "reply": "first answer"})
        await relay.announce_hermes({**JOB, "id": "b", "reply": "second answer"})
        clock.t += 3
        await relay.tick()
        await relay.tick()

    asyncio.run(go())
    assert "first answer" in text_of(s.client_content[0]) and "second answer" in text_of(s.client_content[1])


def test_job_events_and_on_start(tmp_path):
    started, events = [], []

    async def ev(e):
        events.append(e)

    relay = LiveRelay(S(), None, ev)

    async def runner(argv, timeout_s):
        await asyncio.sleep(0.05)
        return 0, "ok\n", ""

    async def go():
        async def on_start(job):
            started.append(job["status"]); await relay.job_event(job)

        async def on_done(job):
            await relay.job_event(job)

        b = HermesBridge(tmp_path, runner=runner, on_start=on_start, on_done=on_done)
        await b.ask("do a thing")
        await b.wait_idle()

    asyncio.run(go())
    assert started == ["running"]
    jobs = [e for e in events if e["type"] == "job"]
    assert [j["status"] for j in jobs] == ["running", "done"]
    assert jobs[0]["task"] == "do a thing" and "seconds" in jobs[1]


def test_ingest_file_rules(tmp_path):
    r = ingest_file("notes.md", "text/markdown", "ਸਤ ਸ੍ਰੀ ਅਕਾਲ\nhello".encode(), tmp_path)
    assert r["ok"] and r["kind"] == "text" and "ਸਤ ਸ੍ਰੀ ਅਕਾਲ" in r["text"]
    assert Path(r["path"]).parent == tmp_path
    evil = ingest_file("../../.ssh/authorized_keys", "text/plain", b"x", tmp_path)
    assert evil["ok"] and Path(evil["path"]).parent == tmp_path and not Path(evil["path"]).name.startswith(".")
    big = ingest_file("big.txt", "text/plain", b"x" * (10 * 1024 * 1024 + 1), tmp_path)
    assert big["ok"] is False
    img = ingest_file("pic.jpg", "image/jpeg", b"\xff\xd8\xff" + b"0" * 100, tmp_path)
    assert img["ok"] and img["kind"] == "image"
    bad = ingest_file("prog.exe", "application/octet-stream", b"MZ", tmp_path)
    assert bad["kind"] == "unsupported"


def test_relay_handle_file(tmp_path, monkeypatch):
    monkeypatch.setenv("SEVEN_UPLOADS", str(tmp_path))
    clock = Clock()
    s, events, relay = make(clock)
    b64 = lambda b: base64.b64encode(b).decode()

    async def go():
        await relay.handle_file({"type": "file", "name": "todo.txt", "mime": "text/plain",
                                 "data_b64": b64(b"buy milk")})
        await relay.handle_file({"type": "file", "name": "pic.png", "mime": "image/png",
                                 "data_b64": b64(b"\x89PNG" + b"0" * 50)})
        await relay.handle_file({"type": "file", "name": "x.exe", "mime": "application/x-msdownload",
                                 "data_b64": b64(b"MZ")})

    asyncio.run(go())
    assert "[User shared file todo.txt]" in text_of(s.client_content[0]) and "buy milk" in text_of(s.client_content[0])
    assert any("video" in r and r["video"].mime_type == "image/png" for r in s.realtime)
    kinds = [e.get("kind") for e in events if e["type"] == "file_received"]
    assert kinds == ["text", "image"]
    assert any(e["type"] == "error" for e in events)


