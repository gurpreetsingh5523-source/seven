def test_file_op_and_trash_with_undo(tmp_path):
    reg, undo, _ = build(tmp_path)
    (tmp_path / "Desktop").mkdir()
    f = tmp_path / "Desktop" / "a.txt"
    f.write_text("hi")
    assert call(reg, "file_op", {"op": "move", "src": "~/Desktop/a.txt", "dst": "~/Desktop/b.txt"})["ok"]
    assert not f.exists() and (tmp_path / "Desktop" / "b.txt").exists()
    asyncio.run(undo.undo_last())
    assert f.exists()
    assert call(reg, "file_op", {"op": "copy", "src": str(f), "dst": str(tmp_path / "c.txt")})["ok"]
    assert call(reg, "file_op", {"op": "copy", "src": str(f), "dst": str(tmp_path / "c.txt")})["ok"] is False  # no overwrite
    asyncio.run(undo.undo_last())
    assert not (tmp_path / "c.txt").exists() and f.exists()
    assert call(reg, "file_op", {"op": "mkdir", "src": "~/Projects/new"})["ok"]
    assert (tmp_path / "Projects" / "new").is_dir()
    for bad in ({"op": "move", "src": str(f), "dst": "/tmp/out.txt"},
                {"op": "move", "src": str(f), "dst": "~/.ssh/a.txt"},
                {"op": "copy", "src": str(f), "dst": "~/Library/a.txt"},
                {"op": "move", "src": "~/../../etc/hosts", "dst": "~/hosts"},
                {"op": "explode", "src": str(f), "dst": "~/z"}):
        assert call(reg, "file_op", bad)["ok"] is False, bad
    assert f.exists()
    out = call(reg, "file_trash", {"path": "~/Desktop/a.txt"})
    assert out["ok"] and not f.exists() and any((tmp_path / ".Trash").iterdir())
    asyncio.run(undo.undo_last())
    assert f.read_text() == "hi"


