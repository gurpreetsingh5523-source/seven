class FakeCal:
    def __init__(self, access="full"):
        self._access, self.events, self.deleted = access, [], []

    async def access(self):
        return self._access

    async def list_events(self, start, end):
        return [e for e in self.events if start <= e["start"] < end]

    async def add_event(self, title, start, end, calendar, location, notes):
        eid = f"ev{len(self.events)}"
        self.events.append({"id": eid, "title": title, "start": start, "end": end,
                            "calendar": calendar or "Home", "location": location})
        return eid

    async def delete_event(self, event_id):
        self.deleted.append(event_id)
        self.events = [e for e in self.events if e["id"] != event_id]
        return True


