def test_doc_edit_all_kinds_with_exact_undo(tmp_path):
    import openpyxl
    reg, undo, docs = office(tmp_path)
    d = call(reg, "doc_create", {"kind": "docx", "name": "a", "text": "Hello Rajinder"})["path"]
    before = Path(d).read_bytes()
    assert call(reg, "doc_edit", {"path": d, "action": "replace", "find": "Rajinder", "text": "Gurpreet"})["ok"]
    assert "Gurpreet" in call(reg, "doc_read", {"path": d})["text"]
    assert call(reg, "doc_edit", {"path": d, "action": "replace", "find": "nope", "text": "x"})["ok"] is False
    run(undo.undo_last())
    assert Path(d).read_bytes() == before
    assert call(reg, "doc_edit", {"path": d, "action": "append", "text": "## New part"})["ok"]
    assert "New part" in call(reg, "doc_read", {"path": d})["text"]
    x = call(reg, "doc_create", {"kind": "xlsx", "name": "b", "rows": [["k", "v"]]})["path"]
    assert call(reg, "doc_edit", {"path": x, "action": "set_cell", "cell": "B2", "value": "42"})["ok"]
    assert call(reg, "doc_edit", {"path": x, "action": "append_row", "row": ["z", "7"]})["ok"]
    ws = openpyxl.load_workbook(x).active
    assert ws["B2"].value == 42 and ws["A3"].value == "z"
    assert call(reg, "doc_edit", {"path": x, "action": "set_cell", "cell": "ZZZ0", "value": "1"})["ok"] is False
    pp = call(reg, "doc_create", {"kind": "pptx", "name": "c", "slides": [{"title": "One", "bullets": ["a"]}]})["path"]
    assert call(reg, "doc_edit", {"path": pp, "action": "add_slide", "slide": {"title": "Two", "bullets": ["b"]}})["ok"]
    assert "Slide 2: Two" in call(reg, "doc_read", {"path": pp})["text"]
    pdf = call(reg, "doc_create", {"kind": "pdf", "name": "d", "text": "x"})["path"]
    assert call(reg, "doc_edit", {"path": pdf, "action": "append", "text": "y"})["ok"] is False
    md = docs / "n.md"
    md.write_text("one\n")
    assert call(reg, "doc_edit", {"path": str(md), "action": "append", "text": "two"})["ok"]
    assert md.read_text().splitlines()[-1] == "two"


