def test_docx_create_read_and_undo(tmp_path):
    import docx
    reg, undo, docs = office(tmp_path)
    out = call(reg, "doc_create", {"kind": "docx", "name": "../../evil/report",
                                   "text": "# Monthly report\n## Sales\n- up 10%\nPlain line\n" + GURMUKHI})
    p = Path(out["path"])
    assert out["ok"] and p.parent == docs and p.name == "report.docx"
    d = docx.Document(str(p))
    styles = [(x.style.name, x.text) for x in d.paragraphs]
    assert ("Heading 1", "Monthly report") in styles and ("Heading 2", "Sales") in styles
    assert any(t == "up 10%" and "List" in s for s, t in styles)
    assert any(GURMUKHI in t for _, t in styles)
    again = call(reg, "doc_create", {"kind": "docx", "name": "report", "text": "x"})
    assert Path(again["path"]).name == "report 2.docx" and p.exists()
    r = call(reg, "doc_read", {"path": "report.docx"})
    assert r["ok"] and r["kind"] == "docx" and "Monthly report" in r["text"] and GURMUKHI in r["text"]
    run(undo.undo_last())
    assert not Path(again["path"]).exists() and p.exists()


