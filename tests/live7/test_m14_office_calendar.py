def test_fetch_news_parses_rss_and_refuses_entities():
    rss = """<?xml version="1.0"?><rss><channel><title>BBC News</title>
      <item><title>Real headline one</title><link>https://bbc.co.uk/1</link></item>
      <item><title>Real headline two</title><link>https://bbc.co.uk/2</link></item>
    </channel></rss>"""
    seen = []

    async def fetch(url):
        seen.append(url)
        return rss

    items = run(fetch_news(limit=1, feed="india", fetch=fetch))
    assert seen == [NEWS_FEEDS["india"]] and [i["title"] for i in items] == ["Real headline one"]
    with pytest.raises(ValueError):
        run(fetch_news(feed="http://evil.example/rss", fetch=fetch))

    async def evil(url):
        return '<?xml version="1.0"?><!DOCTYPE r [<!ENTITY x "boom">]><rss><channel><item><title>&x;</title></item></channel></rss>'

    with pytest.raises(Exception):
        run(fetch_news(fetch=evil))


