@contextlib.asynccontextmanager
async def served():
    from live7.server import start_server
    from live7.tools import ToolBridge
    from sentinel_orchestrator import ApprovalGate, AuditLog, LocalSandbox, PolicyEngine, SecretsBroker, ToolRegistry

    async def no(i, d):
        return False

    bridge = ToolBridge(ToolRegistry(), PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                        AuditLog(), ApprovalGate(no, timeout_s=1))

    class S:
        async def send_client_content(self, **kw): pass
        async def send_realtime_input(self, **kw): pass
        async def send_tool_response(self, **kw): pass
        async def receive(self):
            while True:
                await asyncio.sleep(3600)
                yield None

    def factory(**kw):
        @contextlib.asynccontextmanager
        async def cm():
            yield S()
        return cm()

    server = await start_server(factory, bridge, port=0)
    try:
        yield f"http://127.0.0.1:{server.port}/"
    finally:
        await server.close()


def run(coro):
    return asyncio.run(coro)


def test_truthful_ready_state_before_start():
    async def go():
        async with served() as url:
            async with await open_page(url) as p:
                return await p.eval("[document.body.dataset.state, (document.getElementById('state')||{}).textContent||'']")
    ds, label = run(go())
    assert ds == "ready", ds
    assert "ready" in label.lower() or "tap to start" in label.lower(), label


