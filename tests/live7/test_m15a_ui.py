def test_drag_shows_full_window_overlay():
    async def go():
        async with served() as url:
            async with await open_page(url) as p:
                return await p.eval("""(() => {
                  const dt = new DataTransfer(); dt.items.add(new File(['x'], 'a.txt', {type: 'text/plain'}));
                  document.dispatchEvent(new DragEvent('dragenter', {dataTransfer: dt, bubbles: true}));
                  document.dispatchEvent(new DragEvent('dragover', {dataTransfer: dt, bubbles: true}));
                  const o = document.getElementById('drop-overlay'), r = o.getBoundingClientRect();
                  const shown = getComputedStyle(o).display !== 'none' && !o.hidden;
                  return [shown, r.width >= innerWidth * 0.9, r.height >= innerHeight * 0.9]; })()""")
    assert run(go()) == [True, True, True]


def test_contrast_both_themes_and_buttons_labelled():
    async def go():
        res = {}
        async with served() as url:
            for theme in ("dark", "light"):
                async with await open_page(url) as p:
                    await p.send("Emulation.setEmulatedMedia", features=[{"name": "prefers-color-scheme", "value": theme}])
                    await asyncio.sleep(0.4)
                    res[theme] = await p.eval(CONTRAST_JS)
                    res["unlabelled"] = await p.eval(
                        "[...document.querySelectorAll('button')].filter(b => !(b.textContent.trim() || b.getAttribute('aria-label'))).map(b => b.id||b.className)")
        return res
    r = run(go())
    for theme in ("dark", "light"):
        low = [x for x in r[theme] if x["ratio"] < x["need"]]
        assert len(r[theme]) >= 8 and not low, (theme, low[:6])
    assert r["unlabelled"] == []


def test_mobile_drawer_and_no_horizontal_scroll():
    async def go():
        async with served() as url:
            async with await open_page(url, width=390, height=844) as p:
                return await p.eval("""(() => { const $ = id => document.getElementById(id);
                  const onScreen = el => { const r = el.getBoundingClientRect(), s = getComputedStyle(el);
                    return s.display !== 'none' && s.visibility !== 'hidden' && r.right > 0 && r.left < innerWidth && r.width > 0; };
                  const before = onScreen($('work'));
                  const orb = onScreen($('orb'));
                  const t = $('work-toggle'); if (t) t.click();
                  return {scroll: document.documentElement.scrollWidth <= innerWidth, closed: !before, orb,
                          toggle: !!t, opens: onScreen($('work'))}; })()""")
    r = run(go())
    assert r == {"scroll": True, "closed": True, "orb": True, "toggle": True, "opens": True}, r


