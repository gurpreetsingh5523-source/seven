@pytest.mark.skipif(CHROME is None, reason="Chrome not installed")
@pytest.mark.parametrize("reduced", [False, True])
def test_boot_runs_in_real_chrome_and_finishes(reduced):
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url + "boot.html?silent=1", settle_s=0.3) as p:
                if reduced:
                    await p.send("Emulation.setEmulatedMedia", features=[{"name": "prefers-reduced-motion", "value": "reduce"}])
                    await p.send("Page.reload")
                    await asyncio.sleep(0.3)
                mid = await p.eval("""(() => ({bg: [getComputedStyle(document.documentElement).backgroundColor,
                                                       getComputedStyle(document.body).backgroundColor],
                                              letters: document.querySelectorAll('#word span').length,
                                              mark: document.getElementById('mark').textContent.includes('੭')}))()""")
                await asyncio.sleep(4.0)
                done = await p.eval("document.body.dataset.boot")
        return mid, done
    mid, done = asyncio.run(go())
    assert all(b in ("rgba(0, 0, 0, 0)", "transparent") for b in mid["bg"]), mid
    assert mid["letters"] == 5 and mid["mark"] and done == "done"


def test_launcher_ensure_server_logic():
    from live7 import launcher
    calls, state = [], {"up": False}

    def is_up(port):
        return state["up"]

    def start():
        calls.append("start")
        state["up"] = True

    assert launcher.ensure_server(port=7879, start=start, wait_s=2, is_up=is_up) is True and calls == ["start"]
    calls.clear()
    assert launcher.ensure_server(port=7879, start=start, wait_s=2, is_up=is_up) is True and calls == []
    state["up"] = False
    assert launcher.ensure_server(port=7879, start=lambda: None, wait_s=1, is_up=is_up) is False


def test_window_command(tmp_path):
    from live7 import launcher
    fake = tmp_path / "Chrome"
    fake.write_text("")
    cmd = launcher.window_command("http://127.0.0.1:7879/?launch=1", chrome=str(fake), profile=tmp_path / "prof")
    assert cmd[0] == str(fake) and "--app=http://127.0.0.1:7879/?launch=1" in cmd
    assert f"--user-data-dir={tmp_path / 'prof'}" in cmd and "--autoplay-policy=no-user-gesture-required" in cmd
    assert launcher.window_command("http://x/", chrome=str(tmp_path / "missing")) == ["open", "http://x/"]


def test_make_app_bundle(tmp_path):
    from live7 import launcher
    app = launcher.make_app(dest=tmp_path / "7 Live.app", python="/py/bin/python", repo=tmp_path / "repo")
    info = plistlib.loads((app / "Contents" / "Info.plist").read_bytes())
    assert info["CFBundleName"] == "7 Live" and info["CFBundleIdentifier"] == "com.seven.live"
    assert info["CFBundleExecutable"] == "7Live" and info["LSUIElement"] is True
    exe = app / "Contents" / "MacOS" / "7Live"
    body = exe.read_text()
    assert exe.stat().st_mode & stat.S_IXUSR and body.startswith("#!")
    assert "/py/bin/python -m live7.launcher" in body and str(tmp_path / "repo") in body


