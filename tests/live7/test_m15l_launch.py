"""M15L exam — a launch moment for 7 Live, as impressive as the best desktop assistants, and ours.

Hermes: make these pass. Do not edit this file (or tests/live7/cdp.py).
What the user saw and loved in another assistant (Claude observed it frame by frame, 2026-10-07): at
launch a TRANSPARENT layer appears straight on the desktop (no window): a glow bursts with sparkles,
big spaced wordmark letters fade in, a light sweeps across the letters, a tagline pill slides in under
them with a ring rippling outward; ~3 s later it fades and the app window opens. Our version must
reach that level with our own identity, and do one thing more: 7 greets you by voice.

Our identity: the Gurmukhi numeral ੭ (seven) as the mark, wordmark "SEVEN", tagline "LIVE".

1. static/boot.html (served at /boot.html) — the launch animation, HTML/CSS/JS only, inline (no CDNs):
   - html and body background transparent (the native overlay window is clear);
   - #mark contains "੭" (the core that ignites: radial glow + particle burst, canvas or CSS);
   - #word holds 5 <span> letters S E V E N that reveal one by one, then a light sweep (shimmer) passes;
   - #tag pill with text "LIVE", slides in under the word; .ring element(s) ripple outward;
   - a short, quiet synthesised chime with WebAudio (no audio files), skipped if ?silent=1;
   - const BOOT_MS (total length) <= 3500; at the end body.dataset.boot = "done" and, when present,
     window.webkit.messageHandlers.boot.postMessage("done");
   - @media (prefers-reduced-motion: reduce): no movement, just a 600 ms fade, still ends with "done".
2. live7/launcher.py — `python -m live7.launcher` (macOS):
   ensure_server(port=7879, start=None, wait_s=20, is_up=None) -> bool: if nothing answers HTTP 200 on
       http://127.0.0.1:<port>/ it calls start() (default: start `python -m live7` detached, cwd
       the repo, stdout/stderr to ~/.seven/live7.log) and polls until
       up or wait_s; is_up(port)->bool is injectable for tests.
   window_command(url, chrome=CHROME_PATH, profile=~/.seven/chrome-profile) -> list[str]: Chrome in app
       mode: [chrome, "--app=<url>", "--user-data-dir=<profile>", "--window-size=1280,820",
       "--autoplay-policy=no-user-gesture-required", "--no-first-run"]; when Chrome is missing:
       ["open", url].
   show_overlay(url, timeout_s=6): PyObjC borderless, clear, mouse-transparent window over the whole main
       screen at status-window level, WKWebView with drawsBackground off, message handler "boot"; closes
       on "done" or timeout (fades out 250 ms). Must not crash when run without a display: catch and skip.
   main(): ensure_server, then show_overlay(".../boot.html") and, as the overlay finishes, run
       window_command(".../?launch=1"). Exit code 0 even if the overlay fails.
   make_app(dest=~/Applications/7 Live.app, python=sys.executable, repo=<repo>) -> Path: builds a real
       app bundle: Contents/Info.plist (CFBundleName "7 Live", CFBundleIdentifier "com.seven.live",
       CFBundleExecutable "7Live", LSUIElement true) and Contents/MacOS/7Live (executable shell script that
       execs "<python> -m live7.launcher" with cwd = repo). CLI: `python -m live7.launcher --make-app`.
3. Greeting: static/live.html, when the URL has ?launch=1 AND the microphone permission is already
   "granted" (navigator.permissions.query), starts automatically (same code path as the Start button) and
   sends {"type": "launch"} once connected. live7.relay.LiveRelay.handle_launch() sends ONE user turn that
   starts with "[Launch]" asking 7 to greet the user in one short sentence in their language and offer the
   daily briefing (do not read it unasked). server.py routes {"type":"launch"} to it.
"""

