def run_page(js, width=1280, height=800, reduced=False):
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url, width=width, height=height) as p:
                if reduced:
                    await p.send("Emulation.setEmulatedMedia",
                                 features=[{"name": "prefers-reduced-motion", "value": "reduce"}])
                    await p.send("Page.reload")
                    await asyncio.sleep(1.2)
                return await p.eval(js)
    return asyncio.run(go())


@pytestmark_chrome
@pytest.mark.parametrize("width,height", [(1280, 800), (390, 844)])
def test_page_news_panels(width, height):
    r = run_page(NEWS_JS, width, height)
    assert r == {"inWork": True, "hiddenFirst": True, "newsShown": True, "noopener": True,
                 "evilRefused": True, "liveShown": True, "liveOnScreen": True, "closed": True}, r


