# ---- 1. news tools ----------------------------------------------------------------------------- #

def news_setup(fail=False):
    from live7.news import register_news_tools
    emitted, fetched = [], []

    async def emit(e):
        emitted.append(e)

    async def fetch_news(limit=5, feed="world"):
        fetched.append((limit, feed))
        if fail:
            raise RuntimeError("network down")
        return [{"title": f"Story {i}", "link": f"https://www.bbc.co.uk/news/{i}", "published": "Thu"}
                for i in range(limit)]

    reg = ToolRegistry()
    register_news_tools(reg, emit, fetch_news=fetch_news)
    return reg, emitted, fetched


def call(reg, name, payload):
    return asyncio.run(reg.get(name).fn(payload))


def test_channels_are_youtube_embeds_and_lookup():
    from live7.news import LIVE_CHANNELS, live_url
    for name in ("Al Jazeera English", "DW News", "Sky News", "France 24 English"):
        assert name in LIVE_CHANNELS, name
    assert all(u.startswith("https://www.youtube.com/embed/") for u in LIVE_CHANNELS.values())
    assert live_url("dw")[0] == "DW News" and live_url("AL JAZEERA")[0] == "Al Jazeera English"
    assert live_url("sky")[1] == LIVE_CHANNELS["Sky News"]
    assert live_url("cartoon network") is None


def test_tools_registered_low_risk():
    reg, _, _ = news_setup()
    for name in ("news_show", "news_live", "news_close"):
        spec = reg.get(name)
        assert spec.risk == RiskLevel.LOW and spec.capabilities == Capability.NONE, name


def test_news_show_emits_headlines():
    reg, emitted, fetched = news_setup()
    r = call(reg, "news_show", {"feed": "world", "limit": 3})
    assert r["ok"] is True and len(r["items"]) == 3 and fetched == [(3, "world")]
    assert emitted == [{"type": "news", "feed": "world", "items": r["items"]}]
    call(reg, "news_show", {"limit": 99})
    assert fetched[-1] == (15, "world")


def test_news_show_bad_feed_and_fetch_error():
    reg, emitted, _ = news_setup()
    assert call(reg, "news_show", {"feed": "mars"})["ok"] is False and emitted == []
    reg2, emitted2, _ = news_setup(fail=True)
    r = call(reg2, "news_show", {"feed": "world"})
    assert r["ok"] is False and "network down" in r["error"] and emitted2 == []


def test_news_live_only_allow_listed_channels():
    from live7.news import LIVE_CHANNELS
    reg, emitted, _ = news_setup()
    r = call(reg, "news_live", {"channel": "dw", "url": "https://evil.example/x"})
    assert r["ok"] is True and r["channel"] == "DW News"
    assert emitted == [{"type": "news_live", "channel": "DW News", "url": LIVE_CHANNELS["DW News"]}]
    bad = call(reg, "news_live", {"channel": "nope", "url": "https://evil.example/x"})
    assert bad["ok"] is False and set(bad["channels"]) == set(LIVE_CHANNELS) and len(emitted) == 1
    assert call(reg, "news_close", {})["ok"] is True and emitted[-1] == {"type": "news_close"}


