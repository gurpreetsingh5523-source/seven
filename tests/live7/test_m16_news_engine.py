ENGINE_JS = r"""
(async () => {
  const E = window.__engine, sleep = ms => new Promise(r => setTimeout(r, ms));
  if (!E) return {missing: true};
  const out = {idleLevel: E.level, reduced: E.reduced};
  const w0 = E.whooshes;
  window.sevenHandleEvent({type: 'tool_started', name: 'news_show'});
  await sleep(600);
  out.startLevel = E.level;
  window.sevenHandleEvent({type: 'tool_started', name: 'news_show'});      // within 1.5 s: no 2nd whoosh
  await sleep(100);
  out.whooshes = E.whooshes - w0;
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(3000);
  out.endLevel = E.level;
  await sleep(200);
  window.sevenHandleEvent({type: 'job', job_id: 'j1', task: 'x', status: 'running', seconds: 0});
  await sleep(600);
  out.jobLevel = E.level;
  return out;
})()
"""


@pytestmark_chrome
def test_engine_spins_up_on_work_and_settles():
    """2026-10-08 the user found the ring lines ugly: no rings any more (see test_m16c_fixes)."""
