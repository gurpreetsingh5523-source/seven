"""M16b exam — "Quantum mesh" orb: a living 3D wire sphere that changes shape as 7 listens and speaks.

Hermes: make these pass. Do not edit this file (or tests/live7/cdp.py).

What the user wants (2026-10-08, after comparing with another desktop assistant they like): the orb should be
a 3D wireframe sphere made of many points and lines that rotates and deforms — big flowing lobes while 7
speaks, gentle ripples while it listens, a fast swirl while it works — with a bright white heart, plus the
M16 seven-colour engine rings around it. Ours goes further: the mesh takes 7's state colour (teal listening,
gold thinking, ...) instead of one fixed colour, and the user can choose the look in Settings.
Write it from scratch on the existing #orb canvas (2D canvas is fine; no libraries, no CDNs).

static/live.html:
1. Mesh: a sphere of latitude x longitude vertices (at least 3000, e.g. 44 x 88), rotated in 3D and projected;
   each vertex radius is displaced by a smooth function of (position, time) whose amplitude ("deform") follows
   the state and the audio level: speaking >= 3 x listening and >= 0.3 (with no audio playing); executing/thinking spins
   faster than listening. Lines along latitudes and longitudes with depth-faded alpha (back faint, front
   bright) and a brighter point at vertices; a bright white core in the centre; colour = the state colour.
2. window.__mesh = {style: "mesh" | "glow", vertices: <count drawn>, deform: <current amplitude>,
   spin: <current rotation speed, rad/s>, rotation: <current angle>, frameMs: <rolling average ms spent
   drawing a frame>}. frameMs must stay under 12 ms at 1280x800 in headless Chrome.
3. Settings panel (#settings-panel) gains two selects, saved like the other settings:
   #orb-style  options "mesh" (label "Quantum mesh", the default) and "glow" (label "Glow orb" — the old orb);
   (#ring-colors was removed with the rings on 2026-10-08.)
   Changing #orb-style switches __mesh.style at once; "glow" draws no mesh (__mesh.vertices === 0).
4. prefers-reduced-motion: rotation does not change and deform stays <= the listening value.
5. Everything from M15a/M16 keeps passing (orb core never covered by opaque elements, contrast, labels).
"""

import asyncio
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from cdp import CHROME, open_page  # noqa: E402

pytestmark = pytest.mark.skipif(CHROME is None, reason="Chrome not installed")


def run_page(js, reduced=False):
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url, width=1280, height=800) as p:
                if reduced:
                    await p.send("Emulation.setEmulatedMedia",
                                 features=[{"name": "prefers-reduced-motion", "value": "reduce"}])
                    await p.send("Page.reload")
                    await asyncio.sleep(1.2)
                return await p.eval(js)
    return asyncio.run(go())


MESH_JS = r"""
(async () => {
  const M = window.__mesh, sleep = ms => new Promise(r => setTimeout(r, ms));
  if (!M) return {missing: true};
  const out = {style: M.style, vertices: M.vertices};
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(1500);
  out.listenDeform = M.deform; out.listenSpin = M.spin;
  const r0 = M.rotation; await sleep(400); out.turned = Math.abs(M.rotation - r0);
  window.sevenHandleEvent({type: 'state', state: 'speaking'});
  await sleep(1500);
  out.speakDeform = M.deform;
  window.sevenHandleEvent({type: 'tool_started', name: 'x'});
  await sleep(1500);
  out.workSpin = M.spin;
  await sleep(1000);
  out.frameMs = M.frameMs;
  return out;
})()
"""


def test_mesh_is_default_and_deforms_by_state():
    r = run_page(MESH_JS)
    assert not r.get("missing"), "window.__mesh missing"
    assert r["style"] == "mesh" and r["vertices"] >= 3000, r
    assert r["turned"] > 0, r
    assert r["listenDeform"] > 0 and r["speakDeform"] >= 3 * r["listenDeform"] and r["speakDeform"] >= 0.3, r
    assert r["workSpin"] > r["listenSpin"], r
    assert r["frameMs"] < 12, r


SETTINGS_JS = r"""
(async () => {
  const $ = id => document.getElementById(id), sleep = ms => new Promise(r => setTimeout(r, ms));
  const out = {};
  out.inPanel = !!$('orb-style') && $('settings-panel').contains($('orb-style'));
  if (!out.inPanel) return out;
  out.styleOpts = [...$('orb-style').options].map(o => [o.value, o.textContent.trim()]);
  out.defaults = [$('orb-style').value];
  $('orb-style').value = 'glow'; $('orb-style').dispatchEvent(new Event('change', {bubbles: true}));
  await sleep(300);
  out.glow = [window.__mesh.style, window.__mesh.vertices];
  $('orb-style').value = 'mesh'; $('orb-style').dispatchEvent(new Event('change', {bubbles: true}));
  await sleep(300);
  out.meshBack = window.__mesh.style;
  return out;
})()
"""


def test_settings_switch_orb_style():
    r = run_page(SETTINGS_JS)
    assert r.get("inPanel") is True, r
    assert ["mesh", "Quantum mesh"] in r["styleOpts"] and ["glow", "Glow orb"] in r["styleOpts"], r
    assert r["defaults"] == ["mesh"], r
    assert r["glow"] == ["glow", 0] and r["meshBack"] == "mesh", r


REDUCED_JS = r"""
(async () => {
  const M = window.__mesh, sleep = ms => new Promise(r => setTimeout(r, ms));
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(1200);
  const listen = M.deform;
  window.sevenHandleEvent({type: 'state', state: 'speaking'});
  await sleep(1200);
  const r0 = M.rotation; await sleep(500);
  return {turned: Math.abs(M.rotation - r0), speak: M.deform, listen};
})()
"""


def test_reduced_motion_mesh_is_still():
    r = run_page(REDUCED_JS, reduced=True)
    assert r["turned"] == 0 and r["speak"] <= r["listen"] + 1e-9, r
