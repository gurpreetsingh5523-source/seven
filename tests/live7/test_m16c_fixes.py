# ---- 1a. folder resolution ------------------------------------------------------------------------ #

def test_resolve_folder(tmp_path):
    from capabilities import resolve_folder
    (tmp_path / "Downloads").mkdir()
    (tmp_path / "Desktop" / "tools").mkdir(parents=True)
    assert resolve_folder("downloads", home=tmp_path) == tmp_path / "Downloads"
    assert resolve_folder("Desktop/tools", home=tmp_path) == tmp_path / "Desktop" / "tools"
    assert resolve_folder(str(tmp_path / "Desktop"), home=tmp_path) == tmp_path / "Desktop"
    assert resolve_folder("/Users/7", home=tmp_path) is None
    assert resolve_folder("music", home=tmp_path) is None
    assert resolve_folder("~", home=None) == Path.home()


def test_file_organizer_error_names_home(tmp_path):
    from capabilities import file_organizer
    with pytest.raises(Exception) as e:
        asyncio.run(file_organizer({"folder": "/Users/7", "dry_run": True}))
    msg = str(e.value)
    assert "folder not found" in msg and str(Path.home()) in msg


# ---- 1b/1c. bridge ------------------------------------------------------------------------------- #

def make(prechecks=None, fail=False):
    asked, ran = [], []

    async def org(p):
        ran.append(p)
        if fail:
            raise RuntimeError("disk on fire")
        return {"moved": 0}

    reg = ToolRegistry()
    reg.register(ToolSpec("file_organizer", org, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT))

    async def cb(intent, decision):
        asked.append(intent.payload)
        return True

    from live7.tools import ToolBridge
    kw = {} if prechecks is None else {"prechecks": prechecks}
    audit = AuditLog()
    bridge = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                        audit, ApprovalGate(cb, timeout_s=5), **kw)
    return bridge, asked, ran, audit


def test_default_precheck_stops_bad_folder_before_approval(tmp_path):
    from live7.tools import DEFAULT_PRECHECKS
    assert "file_organizer" in DEFAULT_PRECHECKS
    assert DEFAULT_PRECHECKS["file_organizer"]({"folder": "/Users/7"})
    assert DEFAULT_PRECHECKS["file_organizer"]({"folder": str(tmp_path)}) is None
    bridge, asked, ran, audit = make()
    r = asyncio.run(bridge.dispatch("file_organizer", {"folder": "/Users/7", "dry_run": False}))
    assert r["ok"] is False and r.get("precheck") is True and asked == [] and ran == []
    assert "live_tool_precheck_failed" in [e["event"] for e in audit._entries]


def test_failed_run_is_not_asked_again(tmp_path):
    bridge, asked, ran, audit = make(prechecks={}, fail=True)

    async def go():
        a = await bridge.dispatch("file_organizer", {"folder": str(tmp_path), "dry_run": False})
        b = await bridge.dispatch("file_organizer", {"folder": str(tmp_path), "dry_run": False})
        return a, b

    a, b = asyncio.run(go())
    assert a["ok"] is False and "disk on fire" in a["error"]
    assert b["ok"] is False and "failed" in b["error"] and "do not retry" in b["error"]
    assert len(asked) == 1 and len(ran) == 1


def test_prompt_names_home_folder():
    src = (ROOT / "live7" / "__main__.py").read_text(encoding="utf-8")
    assert "home folder" in src.lower() and "Path.home()" in src


