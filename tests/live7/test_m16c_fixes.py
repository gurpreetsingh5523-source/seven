FLARE_JS = r"""
(async () => {
  const sleep = ms => new Promise(r => setTimeout(r, ms));
  const E = window.__engine, M = window.__mesh;
  await sleep(500);
  const out = {rings: E && E.rings, bgRings: M && M.bgRings, ringSetting: !!document.getElementById('ring-colors'),
               idleFlare: M && M.flare};
  window.sevenHandleEvent({type: 'tool_started', name: 'x'});
  await sleep(600);
  out.workFlare = M.flare;
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(3000);
  out.endFlare = M.flare;
  return out;
})()
"""


@pytest.mark.skipif(CHROME is None, reason="Chrome not installed")
def test_no_ring_lines_and_mesh_flares_on_work():
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url, width=1280, height=800) as p:
                return await p.eval(FLARE_JS)
    r = asyncio.run(go())
    assert r["rings"] == 0 and r["bgRings"] == 0 and r["ringSetting"] is False, r
    assert r["idleFlare"] < 0.2 and r["workFlare"] > 0.5 and r["endFlare"] < 0.2, r
