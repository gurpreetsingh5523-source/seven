def run_page(js, reduced=False):
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url, width=1280, height=800) as p:
                if reduced:
                    await p.send("Emulation.setEmulatedMedia",
                                 features=[{"name": "prefers-reduced-motion", "value": "reduce"}])
                    await p.send("Page.reload")
                    await asyncio.sleep(1.2)
                return await p.eval(js)
    return asyncio.run(go())


ORBIT_JS = r"""
(async () => {
  const O = window.__orbits, M = window.__mesh, sleep = ms => new Promise(r => setTimeout(r, ms));
  if (!O) return {missing: true};
  const snap = () => ({n: O.normals.map(v => [...v]), r: [...O.radii]});
  await sleep(800);
  const out = {count: O.count, spins: [...O.spins], sparkles: O.sparkles, restSpeed: O.speed,
               restMeshSpin: M.spin, rings: window.__engine.rings, bgRings: M.bgRings};
  const s0 = snap(); const rs = [];
  for (let i = 0; i < 15; i++) { await sleep(100); rs.push([...O.radii]); }
  const s1 = snap();
  out.n0 = s0.n; out.n1 = s1.n; out.radiiSeries = rs;
  window.sevenHandleEvent({type: 'tool_started', name: 'x'});
  await sleep(800);
  out.workSpeed = O.speed; out.workMeshSpin = M.spin;
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(3000);
  out.endSpeed = O.speed;
  out.frameMs = M.frameMs;
  return out;
})()
"""


def angle(a, b):
    dot = abs(sum(x * y for x, y in zip(a, b)))          # a plane = +/- normal
    return math.degrees(math.acos(max(-1.0, min(1.0, dot))))


def test_orbits_distinct_planes_directions_and_breathing():
    r = run_page(ORBIT_JS)
    assert not r.get("missing"), "window.__orbits missing"
    assert 5 <= r["count"] <= 9 and len(r["n0"]) == r["count"], r["count"]
    for i in range(r["count"]):
        for j in range(i + 1, r["count"]):
            assert angle(r["n0"][i], r["n0"][j]) > 20, (i, j, r["n0"][i], r["n0"][j])
    assert any(s > 0 for s in r["spins"]) and any(s < 0 for s in r["spins"]), r["spins"]
    assert max(angle(a, b) for a, b in zip(r["n0"], r["n1"])) > 0.2, "planes do not tumble"
    for k in range(r["count"]):
        series = [row[k] for row in r["radiiSeries"]]
        assert max(series) - min(series) > 0.002, ("orbit does not breathe", k)
        assert all(1.1 <= v <= 1.95 for v in series), series
    assert r["sparkles"] >= 6
    assert r["rings"] == 0 and r["bgRings"] == 0


def test_slow_at_rest_fast_on_work():
    r = run_page(ORBIT_JS)
    assert not r.get("missing"), "window.__orbits missing"
    assert all(abs(s * r["restSpeed"]) <= 0.25 for s in r["spins"]), (r["spins"], r["restSpeed"])
    assert r["restMeshSpin"] <= 0.12, r["restMeshSpin"]
    assert r["workSpeed"] >= 4 and r["workMeshSpin"] >= 1.0, (r["workSpeed"], r["workMeshSpin"])
    assert r["endSpeed"] < 1.5, r["endSpeed"]
    assert r["frameMs"] < 12, r["frameMs"]


