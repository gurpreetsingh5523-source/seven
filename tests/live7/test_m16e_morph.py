from cdp import CHROME, open_page  # noqa: E402

pytestmark = pytest.mark.skipif(CHROME is None, reason="Chrome not installed")


def run_page(js, reduced=False):
    from test_m15a_ui import served

    async def go():
        async with served() as url:
            async with await open_page(url, width=1280, height=800) as p:
                if reduced:
                    await p.send("Emulation.setEmulatedMedia",
                                 features=[{"name": "prefers-reduced-motion", "value": "reduce"}])
                    await p.send("Page.reload")
                    await asyncio.sleep(1.2)
                return await p.eval(js)
    return asyncio.run(go())


MORPH_JS = r"""
(async () => {
  const O = window.__orbits, sleep = ms => new Promise(r => setTimeout(r, ms));
  if (!O || typeof O.profile !== 'function' || typeof O.lift !== 'function') return {missing: true};
  await sleep(600);
  const N = 24, snap = () => ({p: [...Array(O.count).keys()].map(i => O.profile(i, N)),
                               l: [...Array(O.count).keys()].map(i => O.lift(i, N)),
                               c: O.centers.map(v => [...v])});
  const a = snap(); const restMorph = O.morph; let maxExtent = O.extent;
  const watch = setInterval(() => { maxExtent = Math.max(maxExtent, O.extent); }, 50);
  await sleep(2000);
  const b = snap();
  window.sevenHandleEvent({type: 'tool_started', name: 'x'});
  await sleep(900);
  const workMorph = O.morph;
  window.sevenHandleEvent({type: 'state', state: 'listening'});
  await sleep(3000);
  const endMorph = O.morph;
  window.sevenHandleEvent({type: 'state', state: 'speaking'});
  await sleep(900);
  const speakMorph = O.morph;
  const c = snap(); clearInterval(watch);
  return {count: O.count, a, b, c, restMorph, workMorph, endMorph, speakMorph, frameMs: window.__mesh.frameMs,
          samples: O.samples, maxExtent, pxRatio: O.pxRatio};
})()
"""


def maxdiff(x, y):
    return max(abs(p - q) for p, q in zip(x, y))


def test_orbits_morph_by_themselves_and_differ():
    r = run_page(MORPH_JS)
    assert not r.get("missing"), "__orbits.profile/lift missing"
    n = r["count"]
    a, b = r["a"], r["b"]
    for i in range(n):
        assert maxdiff(a["p"][i], b["p"][i]) > 0.03, ("orbit shape does not change", i)
    for i in range(n):
        for j in range(i + 1, n):
            assert maxdiff(a["p"][i], a["p"][j]) > 0.03, ("two orbits have the same shape", i, j)
    assert max(max(p) - min(p) for p in a["p"]) > 0.12, "all orbits are still near-circles"
    assert any(abs(v) > 0.01 for l in a["l"] for v in l), "no out-of-plane lift"
    assert all(sum(v * v for v in c) ** 0.5 <= 0.25 for c in a["c"]), a["c"]
    assert max(maxdiff(x, y) for x, y in zip(a["c"], b["c"])) > 0.002, "centres do not move"


def test_shapes_stay_tasteful_smooth_and_on_screen():
    r = run_page(MORPH_JS)
    assert not r.get("missing"), "__orbits.profile/lift missing"
    for snap in (r["a"], r["b"], r["c"]):
        assert all(0.65 <= v <= 1.35 for p in snap["p"] for v in p), "profile out of 0.65..1.35"
        assert all(abs(v) <= 0.3 for l in snap["l"] for v in l), "lift too big"
    assert r["samples"] >= 160, r["samples"]
    assert r["maxExtent"] is not None and r["maxExtent"] <= 0.92, r["maxExtent"]
    assert r.get("pxRatio") is not None and r["pxRatio"] >= 1.15, r.get("pxRatio")


def test_morph_strength_follows_state():
    r = run_page(MORPH_JS)
    assert not r.get("missing"), "__orbits.profile/lift missing"
    assert 0.2 <= r["restMorph"] <= 0.5, r["restMorph"]
    assert r["workMorph"] >= 0.7 and r["speakMorph"] >= 0.7, (r["workMorph"], r["speakMorph"])
    assert r["endMorph"] < 0.5, r["endMorph"]
    assert r["frameMs"] < 12, r["frameMs"]


