STARS_MOVE_JS = r"""
(async () => {
  const sleep = ms => new Promise(r => setTimeout(r, ms));
  await sleep(500);
  const S = window.__starfield && window.__starfield.stars;
  if (!S) return {missing: true};
  const a = S.map(s => [s.x, s.y, s.z]);
  await sleep(1500);
  const b = S.map(s => [s.x, s.y, s.z]);
  let moved = 0;
  for (let i = 0; i < a.length; i++) if (Math.abs(a[i][2] - b[i][2]) > 0.01) moved++;
  return {n: S.length, moved, drawn: window.__mesh.starsDrawn};
})()
"""


def test_stars_drift_in_depth():
    """User 2026-10-10: the stars did not move. They now fly slowly toward the viewer (3D)."""
    r = run_page(STARS_MOVE_JS)
    assert not r.get("missing"), r
    assert r["n"] >= 150 and r["moved"] >= 0.8 * r["n"] and r["drawn"] > 50, r


def test_stars_still_with_reduced_motion():
    r = run_page(STARS_MOVE_JS, reduced=True)
    assert r["moved"] == 0, r
