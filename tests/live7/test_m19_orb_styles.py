PARTICLES_JS = PICK + r"""
(async () => {
  await pick('particles');
  const P = window.__particles;
  if (!P || !window.__setBands || !window.__bands) return {missing: true};
  window.sevenHandleEvent({type: 'state', state: 'speaking'});
  window.__setBands([0, 0, 0], 2500); await sleep(2200);
  const rest = {radius: P.radius, wave: P.wave, sparks: P.sparks, bands: [...window.__bands]};
  window.__setBands([1, 0, 0], 1500); await sleep(1200);
  const low = P.radius;
  window.__setBands([0, 1, 0], 1500); await sleep(1200);
  const mid = P.wave;
  window.__setBands([0, 0, 1], 1500); await sleep(1000);
  const high = P.sparks;
  await sleep(600);
  return {count: P.count, rest, low, mid, high, frameMs: P.frameMs};
})()
"""


def test_voice_orb_reacts_to_three_bands():
    r = run_page(PARTICLES_JS)
    assert not r.get("missing"), "window.__particles / __bands / __setBands missing"
    assert r["count"] >= 4000, r
    rest = r["rest"]
    assert all(0 <= b <= 0.05 for b in rest["bands"]), r
    assert r["low"] >= 1.15 * rest["radius"], r
    assert r["mid"] > 0 and r["mid"] >= 3 * rest["wave"], r
    assert r["high"] >= 10 and rest["sparks"] <= 2, r
    assert r["frameMs"] < 12, r


