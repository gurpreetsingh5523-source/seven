import asyncio
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))


@pytest.mark.parametrize("text", ["Go ahead.", "Sure.", "Yep", "Yes please", "please do", "do it",
                                  "ji haan", "haan ji kar do", "theek hai, kholo"])
def test_more_yes(text):
    from live7.approvals import _verdict
    assert _verdict(text) is True, text


@pytest.mark.parametrize("text", ["don't go ahead", "Don’t do it", "do not", "wait", "no wait",
                                  "na karo", "mat karo", "rehn do", "yes... no, cancel"])
def test_more_no(text):
    from live7.approvals import _verdict
    assert _verdict(text) is False, text


@pytest.mark.parametrize("text", ["what time is it", "tell me about Ludhiana"])
def test_unrelated(text):
    from live7.approvals import _verdict
    assert _verdict(text) is None, text


def q(tool, payload):
    from live7.approvals import _question
    return _question(SimpleNamespace(tool=tool, payload=payload))


def test_question_plain_language():
    for tool, key in (("desktop_open_app", "app"), ("app_open", "name")):
        s = q(tool, {key: "Calculator"})
        assert "open Calculator" in s and s.endswith("Yes or no?") and "_" not in s, s
    s = q("site_open", {"url": "youtube.com"})
    assert "youtube.com" in s and s.endswith("Yes or no?") and "site_open" not in s, s
    s = q("app_quit", {"app": "Music"})
    assert "quit Music" in s and "_" not in s, s
    s = q("file_trash", {"path": "Downloads/old.zip"})
    assert "Downloads/old.zip" in s and "Trash" in s and "file_trash" not in s, s
    s = q("calendar_add", {"title": "Dentist", "start": "2026-10-10 09:00"})
    assert "calendar add" in s and "Dentist" in s and "_" not in s.replace("2026-10-10", "") and s.endswith("Yes or no?"), s
    s = q("undo", {})
    assert "undo" in s and s.endswith("Yes or no?"), s


def test_prompt_lets_the_app_ask():
    src = (ROOT / "live7" / "__main__.py").read_text(encoding="utf-8")
    assert "never ask for confirmation yourself" in src.lower()
    assert "must go through the approval flow — ask and" not in src
    assert "do not retry" in src.lower()


def test_globe_distance_with_country_suffix():
    from skills7 import globe_distance
    r = asyncio.run(globe_distance({"from_city": "Ludhiana, India", "to_city": " Amritsar, Punjab "}))
    assert "error" not in r, r
    assert 120 <= r["distance_km"] <= 128, r
