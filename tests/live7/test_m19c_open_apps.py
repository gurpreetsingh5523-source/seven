def test_validate_runs_before_approval():
    """A call whose validate() fails returns a precheck error and never asks the user."""
    from live7.tools import ToolBridge
    from sentinel_orchestrator import (ToolRegistry, ToolSpec, RiskLevel, Capability, PolicyEngine,
                                       LocalSandbox, SecretsBroker, ApprovalGate)
    import inspect
    asked = []

    async def cb(intent, decision):
        asked.append(intent.tool)
        return True

    def bad(p):
        raise ValueError("no such app")

    async def fn(p):
        return {"ran": True}

    reg = ToolRegistry()
    reg.register(ToolSpec("desktop_open_app", fn, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT, validate=bad))

    class Audit:
        def record(self, *a, **k):
            pass

    sig = inspect.signature(ToolBridge.__init__)
    kwargs = {}
    if "prechecks" in sig.parameters:
        kwargs["prechecks"] = {}
    bridge = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker()), Audit(), ApprovalGate(cb, timeout_s=1),
                        **kwargs)
    r = asyncio.run(bridge.dispatch("desktop_open_app", {"app": "Nope"}))
    assert asked == [], asked
    assert r.get("ok") is False and r.get("precheck") is True and "no such app" in r.get("error", ""), r


@pytest.mark.skipif(sys.platform != "darwin", reason="macOS registry")
def test_live_app_open_defaults_to_really_opening(monkeypatch):
    import asyncio as aio
    launched = []

    async def fake_exec(*argv, **k):
        launched.append(argv)

        class P:
            pid = 1
            returncode = 0

            async def wait(self):
                return 0

            async def communicate(self):
                return (b"", b"")
        return P()

    monkeypatch.setattr(aio, "create_subprocess_exec", fake_exec)
    reg = build()
    spec = reg.get("app_open")
    r = aio.run(spec.fn({"name": "calculator"}))
    assert launched and launched[0][:3] == ("open", "-a", "Calculator"), (launched, r)
