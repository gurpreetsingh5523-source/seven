def test_open_app_runs_open_a_with_resolved_name():
    from live7.mac import open_app
    calls = []

    async def runner(argv, *a, **k):
        calls.append(list(argv))
        return (0, "", "")

    r = asyncio.run(open_app({"app": "calculator"}, runner=runner))
    assert r["ok"] is True and r["opened"] == "Calculator", r
    assert calls == [["open", "-a", "Calculator"]], calls


