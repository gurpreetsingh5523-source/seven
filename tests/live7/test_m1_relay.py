"""M1 exam — relay core in TEXT mode (no network, fake Live session).

Hermes: implement `live7/relay.py`, `live7/tools.py`, `live7/server.py` so these pass.
Do not edit this file.

Interfaces required
-------------------
live7.tools.ToolBridge(registry, policy, sandbox, audit, approval)
    .declarations() -> list[dict]           # {"name","description","parameters"} per registry tool
    async .dispatch(name, args) -> dict     # never raises; routes through PolicyEngine,
                                            # ApprovalGate when needed, sandbox.execute to run
      success          -> {"ok": True, "result": <tool output>}
      unknown tool     -> {"ok": False, "error": "..."}
      policy veto      -> {"ok": False, "error": "...", "vetoed": True}
      not approved     -> {"ok": False, "error": "...", "approved": False}
      tool raised      -> {"ok": False, "error": "<message>"}
    Every dispatch writes an audit record whose event name starts with "live_tool".

live7.relay.LiveRelay(session, bridge, send_event)
    session: object with async send_client_content(turns=, turn_complete=),
             async send_tool_response(function_responses=), async-iterable receive()
    send_event: async callable(dict) -> None  (JSON events to the browser)
    async .handle_client(msg: dict)   # {"type":"text","text":...}; anything else -> error event
    async .handle_response(resp)      # one google.genai.types.LiveServerMessage
    async .pump()                     # handle_response for every message from session.receive()

live7.server
    DEFAULT_HOST == "127.0.0.1"
    assert_loopback(host) -> None, raises ValueError for any non-loopback host
"""

