class FakeSession:
    def __init__(self, messages=()):
        self.messages = list(messages)
        self.client_content = []
        self.tool_responses = []

    async def send_client_content(self, turns=None, turn_complete=None):
        self.client_content.append((turns, turn_complete))

    async def send_tool_response(self, function_responses=None):
        self.tool_responses.append(list(function_responses))

    async def receive(self):
        # Like google-genai: messages are consumed, and the iterator ends at
        # each turn_complete (the relay must call receive() again next turn).
        while self.messages:
            m = self.messages.pop(0)
            yield m
            sc = getattr(m, "server_content", None)
            if sc is not None and getattr(sc, "turn_complete", False):
                return


def make_bridge(approve=True, tmp_path=None):
    calls = []

    async def sysmon(p):
        calls.append(("system_monitor", p))
        return {"cpu_pct": 12.5}

    async def boom(p):
        raise RuntimeError("tool exploded")

    async def open_site(p):
        calls.append(("site_open", p))
        return {"opened_url": p.get("url")}

    async def evil(p):
        calls.append(("evil", p))
        return {}

    reg = ToolRegistry()
    reg.register(ToolSpec("system_monitor", sysmon, RiskLevel.LOW, Capability.NONE))
    reg.register(ToolSpec("boom", boom, RiskLevel.LOW, Capability.NONE))
    reg.register(ToolSpec("site_open", open_site, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT))
    reg.register(ToolSpec("evil", evil, RiskLevel.MEDIUM,
                          Capability.UNTRUSTED_INPUT | Capability.SENSITIVE_ACCESS | Capability.EXTERNAL_EFFECT))

    asked = []

    async def gate(intent, decision):
        asked.append(intent.tool)
        return approve

    audit = AuditLog(tmp_path / "audit.jsonl" if tmp_path else None)
    bridge = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                        audit, ApprovalGate(gate, timeout_s=2))
    return bridge, calls, asked, audit


def run(coro):
    return asyncio.run(coro)


# ---------------------------------------------------------------- ToolBridge --

def test_declarations_cover_every_registered_tool(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    decl = bridge.declarations()
    names = {d["name"] for d in decl}
    assert names == {"system_monitor", "boom", "site_open", "evil"}
    for d in decl:
        assert isinstance(d.get("description"), str) and d["description"]
        assert d.get("parameters", {}).get("type") in ("OBJECT", "object")


def test_low_risk_tool_runs_without_approval(tmp_path):
    bridge, calls, asked, audit = make_bridge(tmp_path=tmp_path)
    res = run(bridge.dispatch("system_monitor", {}))
    assert res == {"ok": True, "result": {"cpu_pct": 12.5}}
    assert calls == [("system_monitor", {})]
    assert asked == []


def test_high_risk_tool_asks_and_runs_only_when_approved(tmp_path):
    bridge, calls, asked, _ = make_bridge(approve=True, tmp_path=tmp_path)
    res = run(bridge.dispatch("site_open", {"url": "https://example.com"}))
    assert res["ok"] is True and asked == ["site_open"]

    bridge, calls, asked, _ = make_bridge(approve=False, tmp_path=tmp_path)
    res = run(bridge.dispatch("site_open", {"url": "https://example.com"}))
    assert res["ok"] is False and res.get("approved") is False
    assert calls == []                                   # never ran


def test_rule_of_two_veto_never_runs_or_asks(tmp_path):
    bridge, calls, asked, _ = make_bridge(tmp_path=tmp_path)
    res = run(bridge.dispatch("evil", {}))
    assert res["ok"] is False and res.get("vetoed") is True
    assert calls == [] and asked == []


def test_unknown_tool_and_crashing_tool_never_raise(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    r1 = run(bridge.dispatch("does_not_exist", {}))
    r2 = run(bridge.dispatch("boom", {}))
    assert r1["ok"] is False and "error" in r1
    assert r2["ok"] is False and "tool exploded" in r2["error"]


def test_every_dispatch_is_audited_and_chain_valid(tmp_path):
    bridge, _, _, audit = make_bridge(tmp_path=tmp_path)
    for name in ("system_monitor", "does_not_exist", "evil", "boom"):
        run(bridge.dispatch(name, {}))
    events = [e["event"] for e in audit._entries] if hasattr(audit, "_entries") else None
    if events is None:  # fall back to the on-disk log
        import json
        events = [json.loads(l)["event"] for l in (tmp_path / "audit.jsonl").read_text().splitlines()]
    assert sum(1 for e in events if e.startswith("live_tool")) >= 4
    assert audit.verify() is True


