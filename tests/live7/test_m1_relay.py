def collect():
    events = []

    async def send(ev):
        assert isinstance(ev, dict) and "type" in ev
        events.append(ev)

    return events, send


def test_browser_text_goes_to_live_session_as_user_turn(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    s = FakeSession()
    events, send = collect()
    relay = LiveRelay(s, bridge, send)
    run(relay.handle_client({"type": "text", "text": "ਸਤ ਸ੍ਰੀ ਅਕਾਲ"}))
    assert len(s.client_content) == 1
    turns, complete = s.client_content[0]
    assert complete is True
    content = turns[0] if isinstance(turns, list) else turns
    assert content.role == "user" and content.parts[0].text == "ਸਤ ਸ੍ਰੀ ਅਕਾਲ"


def test_unknown_client_message_yields_error_event_not_crash(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    s = FakeSession()
    events, send = collect()
    run(LiveRelay(s, bridge, send).handle_client({"type": "launch_missiles"}))
    assert s.client_content == []
    assert any(e["type"] == "error" for e in events)


def test_transcripts_and_turn_complete_become_events(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    msgs = [
        types.LiveServerMessage(server_content=types.LiveServerContent(
            input_transcription=types.Transcription(text="what is my ram"))),
        types.LiveServerMessage(server_content=types.LiveServerContent(
            output_transcription=types.Transcription(text="Your RAM is fine."))),
        types.LiveServerMessage(server_content=types.LiveServerContent(turn_complete=True)),
    ]
    s = FakeSession(msgs)
    events, send = collect()
    run(LiveRelay(s, bridge, send).pump())
    types_seen = [e["type"] for e in events]
    assert {"type": "transcript_in", "text": "what is my ram"} in events
    assert {"type": "transcript_out", "text": "Your RAM is fine."} in events
    assert types_seen.index("transcript_in") < types_seen.index("transcript_out")
    assert any(e["type"] == "state" and e.get("state") == "listening" for e in events)


def test_tool_call_routes_through_bridge_and_answers_model(tmp_path):
    bridge, calls, asked, _ = make_bridge(tmp_path=tmp_path)
    msg = types.LiveServerMessage(tool_call=types.LiveServerToolCall(function_calls=[
        types.FunctionCall(id="c1", name="system_monitor", args={}),
        types.FunctionCall(id="c2", name="evil", args={}),
    ]))
    s = FakeSession([msg])
    events, send = collect()
    run(LiveRelay(s, bridge, send).pump())
    assert calls == [("system_monitor", {})]               # evil vetoed, never ran
    assert len(s.tool_responses) == 1
    frs = {fr.id: fr for fr in s.tool_responses[0]}
    assert set(frs) == {"c1", "c2"}
    assert frs["c1"].name == "system_monitor" and frs["c1"].response["ok"] is True
    assert frs["c2"].response["ok"] is False
    started = [e for e in events if e["type"] == "tool_started"]
    finished = [e for e in events if e["type"] == "tool_result"]
    assert [e["name"] for e in started] == ["system_monitor", "evil"]
    assert len(finished) == 2
    assert any(e["type"] == "state" and e.get("state") == "executing" for e in events)


def test_interrupted_flag_is_forwarded(tmp_path):
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    s = FakeSession([types.LiveServerMessage(server_content=types.LiveServerContent(interrupted=True))])
    events, send = collect()
    run(LiveRelay(s, bridge, send).pump())
    assert any(e["type"] == "interrupted" for e in events)


