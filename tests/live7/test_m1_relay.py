def test_server_is_loopback_only():
    assert DEFAULT_HOST == "127.0.0.1"
    for ok in ("127.0.0.1", "localhost", "::1"):
        assert_loopback(ok)
    for bad in ("0.0.0.0", "::", "192.168.0.10", "", "example.com"):
        with pytest.raises(ValueError):
            assert_loopback(bad)


def test_pump_keeps_listening_after_each_turn(tmp_path):
    # Regression (2026-10-05, found live in Safari): receive() ends at every
    # turn_complete; a pump that iterates it only once answers one question
    # and then goes silent.
    bridge, *_ = make_bridge(tmp_path=tmp_path)
    turn = lambda t: [
        types.LiveServerMessage(server_content=types.LiveServerContent(
            output_transcription=types.Transcription(text=t))),
        types.LiveServerMessage(server_content=types.LiveServerContent(turn_complete=True)),
    ]
    s = FakeSession(turn("one") + turn("two") + turn("three"))
    events, send = collect()
    run(LiveRelay(s, bridge, send).pump())
    said = [e["text"] for e in events if e["type"] == "transcript_out"]
    assert said == ["one", "two", "three"]
