class RemRunner:
    """A fake Reminders app: open reminders as (id, name, due)."""

    def __init__(self, items):
        self.items = list(items)
        self.calls = []
        self.created = []
        self.completed = []
        self.deleted = []

    def scripts(self, argv):
        return [argv[i + 1] for i, a in enumerate(argv[:-1]) if a == "-e"]

    async def __call__(self, argv, input=None, timeout_s=15):
        self.calls.append(list(argv))
        src = "\n".join(self.scripts(argv))
        args = [a for i, a in enumerate(argv) if i > 0 and argv[i - 1] != "-e" and a != "-e"]
        if "make new reminder" in src:
            self.created.append(args)
            return 0, f"x-apple-reminder://NEW-{len(self.created)}\n", ""
        if "delete" in src:
            self.deleted += [a for a in args if a.startswith("x-apple-reminder://")]
            return 0, "", ""
        if "completed" in src and ("true" in src or "false" in src) and "whose completed is false" not in src:
            self.completed.append((args, "true" in src))
            return 0, "", ""
        if "whose completed is false" in src:
            return 0, "\n".join(f"{i}\t{n}\t{d}" for i, n, d in self.items) + "\n", ""
        return 0, "", ""


ITEMS = [("x-apple-reminder://OLD", "Call for council tax", "Monday, 6 October 2026 at 09:00:00"),
         ("x-apple-reminder://N1", "Call for council tax", ""),
         ("x-apple-reminder://N2", "call for  Council Tax ", ""),
         ("x-apple-reminder://B", "Buy milk", ""),
         ("x-apple-reminder://C", "Car service booking", "")]


def build(items=ITEMS):
    reg, undo, r = ToolRegistry(), UndoStack(), RemRunner(items)
    register_mac_tools(reg, undo=undo, runner=r, home=Path.home())
    return reg, undo, r


def call(reg, name, payload):
    return asyncio.run(reg.get(name).fn(payload))


