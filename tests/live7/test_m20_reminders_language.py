    assert again.get("ok") is False and again.get("duplicate") is True, again
    assert "fail" in again.get("error", "").lower() and "retry" in again.get("error", "").lower(), again
    oks = [k.get("ok") for e, k in rows if e == "live_tool_result"]
    assert oks and all(o is False for o in oks), rows


