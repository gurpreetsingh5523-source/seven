def _bridge(fn_result, audit_rows):
    from live7.tools import ToolBridge
    from sentinel_orchestrator import (ToolSpec, PolicyEngine, LocalSandbox, SecretsBroker, ApprovalGate)
    import inspect

    async def cb(intent, decision):
        return True

    async def fn(p):
        return dict(fn_result)

    reg = ToolRegistry()
    reg.register(ToolSpec("file_trash", fn, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT))

    class Audit:
        def record(self, event, **k):
            audit_rows.append((event, k))

    kwargs = {"prechecks": {}} if "prechecks" in inspect.signature(ToolBridge.__init__).parameters else {}
    return ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker()), Audit(),
                      ApprovalGate(cb, timeout_s=1), **kwargs)


def test_repeat_of_failed_action_is_not_ok():
    rows = []
    b = _bridge({"ok": False, "error": "hidden component in path"}, rows)
    first = asyncio.run(b.dispatch("file_trash", {"path": "~/.calendars/x"}))
    again = asyncio.run(b.dispatch("file_trash", {"path": "~/.calendars/x"}))
