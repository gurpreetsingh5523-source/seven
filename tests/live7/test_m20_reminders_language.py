def test_relay_writes_chatlog(tmp_path):
    from live7.chatlog import ChatLog
    from live7.relay import LiveRelay
    log = ChatLog(tmp_path / "c", clock=lambda: 1791619103.0)

    class Session:
        async def send_client_content(self, **k):
            pass

        async def send_tool_response(self, **k):
            pass

    class Bridge:
        async def dispatch(self, name, args):
            return {"ok": False, "error": "nope"}

    async def send(e):
        pass

    relay = LiveRelay(Session(), Bridge(), send, chatlog=log)

    async def go():
        await relay.handle_client({"type": "text", "text": "delete the tax reminder"})
        fc = SimpleNamespace(id="1", name="reminder_delete", args={"title": "tax"})
        await relay._dispatch_tool_call([fc])
        content = SimpleNamespace(interrupted=False, model_turn=None, turn_complete=False,
                                  input_transcription=SimpleNamespace(text="ਹਾਂ ਜੀ"),
                                  output_transcription=SimpleNamespace(text="Done."))
        msg = SimpleNamespace(server_content=content, tool_call=None, session_resumption_update=None,
                              go_away=None, setup_complete=None, usage_metadata=None)
        await relay.handle_response(msg)
    asyncio.run(go())
    rows = [json.loads(l) for f in sorted((tmp_path / "c").glob("chat-*.jsonl"))
            for l in f.read_text(encoding="utf-8").splitlines()]
    kinds = [r["kind"] for r in rows]
