def make_factory(messages=()):
    made = []

    @contextlib.asynccontextmanager
    async def factory():
        s = FakeSession(messages)
        made.append(s)
        yield s

    return factory, made


def test_server_serves_page_and_relays_websocket():
    from websockets.asyncio.client import connect

    hello = types.LiveServerMessage(server_content=types.LiveServerContent(
        output_transcription=types.Transcription(text="hello")))
    pcm_down = b"\x05\x00" * 50

    async def go():
        factory, made = make_factory([hello, audio_msg(pcm_down)])
        server = await start_server(factory, bridge_with(), port=0)
        try:
            base = f"http://127.0.0.1:{server.port}"
            html = await asyncio.to_thread(lambda: urllib.request.urlopen(base + "/", timeout=5).read().decode())
            async with connect(f"ws://127.0.0.1:{server.port}/live", origin=base) as ws:
                await ws.send(json.dumps({"type": "text", "text": "hi"}))
                await ws.send(b"\x01\x00" * 160)                       # mic frame
                got_text, got_bin = [], []
                for _ in range(10):
                    try:
                        m = await asyncio.wait_for(ws.recv(), 2)
                    except asyncio.TimeoutError:
                        break
                    (got_bin if isinstance(m, bytes) else got_text).append(m)
                    if got_bin and any('"hello"' in t for t in got_text):
                        break
                await asyncio.sleep(0.2)
            return html, got_text, got_bin, made
        finally:
            await server.close()

    html, got_text, got_bin, made = run(go())
    assert "<html" in html.lower()
    assert any(json.loads(t) == {"type": "transcript_out", "text": "hello"} for t in got_text)
    assert pcm_down in got_bin
    s = made[0]
    assert s.client_content and s.client_content[0][1] is True
    assert any("audio" in r and r["audio"].mime_type == "audio/pcm;rate=16000" for r in s.realtime)


def test_server_rejects_foreign_origin_and_non_loopback():
    from websockets.asyncio.client import connect

    async def go():
        factory, made = make_factory()
        server = await start_server(factory, bridge_with(), port=0)
        try:
            with pytest.raises(Exception):
                async with connect(f"ws://127.0.0.1:{server.port}/live", origin="http://evil.example"):
                    pass
            return made
        finally:
            await server.close()

    made = run(go())
    assert made == []                       # no Gemini session opened for the attacker

    factory, _ = make_factory()
    with pytest.raises(ValueError):
        run(start_server(factory, bridge_with(), host="0.0.0.0", port=0))


