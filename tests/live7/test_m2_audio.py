def test_mic_audio_uses_audio_blob_16k_never_media():
    s = FakeSession()
    events, audio, ev, au = recorder()
    relay = LiveRelay(s, bridge_with(), ev, send_audio=au)
    pcm = b"\x01\x00" * 1600
    run(relay.handle_audio(pcm))
    assert len(s.realtime) == 1
    blob = s.realtime[0]["audio"]
    assert blob.data == pcm and blob.mime_type == "audio/pcm;rate=16000"


def test_audio_end_closes_the_stream():
    s = FakeSession()
    events, audio, ev, au = recorder()
    run(LiveRelay(s, bridge_with(), ev, send_audio=au).handle_client({"type": "audio_end"}))
    assert s.realtime == [{"audio_stream_end": True}]


def test_model_audio_goes_to_browser_with_one_speaking_state_per_turn():
    a, b = b"\x10\x00" * 100, b"\x20\x00" * 100
    s = FakeSession()
    events, audio, ev, au = recorder()
    relay = LiveRelay(s, bridge_with(), ev, send_audio=au)

    async def go():
        await relay.handle_response(audio_msg(a))
        await relay.handle_response(audio_msg(b))
        await relay.handle_response(types.LiveServerMessage(
            server_content=types.LiveServerContent(turn_complete=True)))
        await relay.handle_response(audio_msg(a))     # next turn speaks again

    run(go())
    assert audio == [a, b, a]
    speaking = [e for e in events if e == {"type": "state", "state": "speaking"}]
    assert len(speaking) == 2


def test_interrupted_flushes_browser_playback():
    s = FakeSession()
    events, audio, ev, au = recorder()
    run(LiveRelay(s, bridge_with(), ev, send_audio=au).handle_response(
        types.LiveServerMessage(server_content=types.LiveServerContent(interrupted=True))))
    kinds = [e["type"] for e in events]
    assert "interrupted" in kinds and "stop_playback" in kinds


def test_text_model_turn_reaches_browser():
    s = FakeSession()
    events, audio, ev, au = recorder()
    msg = types.LiveServerMessage(server_content=types.LiveServerContent(
        model_turn=types.Content(role="model", parts=[types.Part(text="ਸਤ ਸ੍ਰੀ ਅਕਾਲ ਜੀ")])))
    run(LiveRelay(s, bridge_with(), ev, send_audio=au).handle_response(msg))
    assert {"type": "transcript_out", "text": "ਸਤ ਸ੍ਰੀ ਅਕਾਲ ਜੀ"} in events


