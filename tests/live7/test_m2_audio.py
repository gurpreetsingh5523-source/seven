def test_live_config_and_model_choice(monkeypatch):
    decl = bridge_with("weather_report").declarations()
    cfg = build_live_config(decl, "You are 7.")
    assert isinstance(cfg, types.LiveConnectConfig)
    assert [str(m).split(".")[-1].upper() for m in cfg.response_modalities] == ["AUDIO"]
    assert cfg.input_audio_transcription is not None and cfg.output_audio_transcription is not None
    names = [fd.name if hasattr(fd, "name") else fd["name"]
             for t in cfg.tools for fd in (t.function_declarations if hasattr(t, "function_declarations") else t["function_declarations"])]
    assert names == ["weather_report"]
    si = cfg.system_instruction
    assert "You are 7." in (si if isinstance(si, str) else str(si))
    monkeypatch.delenv("SEVEN_LIVE_MODEL", raising=False)
    assert live_model() == "models/gemini-3.1-flash-live-preview"
    monkeypatch.setenv("SEVEN_LIVE_MODEL", "models/x")
    assert live_model() == "models/x"


