class FakeSession:
    def __init__(self, messages=()):
        self.messages = list(messages)
        self.client_content, self.tool_responses, self.realtime = [], [], []

    async def send_client_content(self, turns=None, turn_complete=None):
        self.client_content.append((turns, turn_complete))

    async def send_tool_response(self, function_responses=None):
        self.tool_responses.append(list(function_responses))

    async def send_realtime_input(self, **kwargs):
        assert "media" not in kwargs, "deprecated media= must never be used"
        self.realtime.append(kwargs)

    async def receive(self):
        # Like google-genai: messages are consumed, and the iterator ends at
        # each turn_complete (the relay must call receive() again next turn).
        while self.messages:
            m = self.messages.pop(0)
            yield m
            sc = getattr(m, "server_content", None)
            if sc is not None and getattr(sc, "turn_complete", False):
                return
        while True:                       # a live session stays open
            await asyncio.sleep(3600)


def bridge_with(*names):
    async def noop(p):
        return {"ok": 1}

    reg = ToolRegistry()
    for n in names:
        reg.register(ToolSpec(n, noop, RiskLevel.LOW, Capability.NONE))

    async def gate(i, d):
        return False

    return ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                      AuditLog(), ApprovalGate(gate, timeout_s=1))


def run(coro):
    return asyncio.run(coro)


def recorder():
    events, audio = [], []

    async def ev(e):
        events.append(e)

    async def au(b):
        audio.append(b)

    return events, audio, ev, au


def audio_msg(pcm, text=None):
    parts = [types.Part(inline_data=types.Blob(data=pcm, mime_type="audio/pcm;rate=24000"))]
    if text:
        parts.append(types.Part(text=text))
    return types.LiveServerMessage(server_content=types.LiveServerContent(
        model_turn=types.Content(role="model", parts=parts)))


