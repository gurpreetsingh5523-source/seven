"""M3 exam — the page: "universe" orb, per-turn captions, states, mute, text box.

Hermes: make these pass. Do not edit this file.
The user's words: "no universe?" — they want a living, animated orb, not a static ball, and
captions that read like sentences, not one word per line.

Required
--------
static/live_core.js — pure logic, no DOM access at load time. Must work both as a classic
  <script> in the browser AND under node via:  if (typeof module !== "undefined") module.exports = {...}
  exports:
    STATES: array of the 8 state names
      ["idle","listening","thinking","executing","speaking","muted","error","reconnecting"]
    STATE_STYLE[state] -> {color: "#rrggbb", speed: number>0, pulse: number>=0}; 8 distinct colors
    mergeCaption(lines, who, text) -> new array (do not mutate the input).
        lines items are {who, text, open}. If the last line is open and has the same `who`,
        append text to it; otherwise push {who, text, open:true}. Joining rule: fragments are
        trimmed and joined with ONE space, except no space before , . ! ? ; : ' ) and none
        after ( . Empty/whitespace text is ignored.
    endTurn(lines) -> new array with every line closed (open:false).
    orbParams(state, level, t) -> {color, radius, spin, particles}
        particles >= 60; radius grows with level (0..1) and is always > 0;
        unknown state falls back to "idle" style; deterministic for the same inputs.
static/live.html — loads /live_core.js; has <canvas id="orb"> animated with requestAnimationFrame
  (particles / waves driven by orbParams and a live audio level from AnalyserNode for mic AND
  playback); captions rendered from mergeCaption/endTurn (endTurn on turn end / state listening);
  a text box id="say" that sends {"type":"text","text":...}; a mute button id="mute" that stops
  sending mic frames and shows the muted state; the debug line hidden by default, toggled with "d".
live7.server — also serves GET /live_core.js as application/javascript.
"""

import asyncio
import contextlib
import json
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
CORE = ROOT / "static" / "live_core.js"
PAGE = ROOT / "static" / "live.html"

NODE = shutil.which("node")
pytestmark = pytest.mark.skipif(NODE is None, reason="node not installed")


def js(expr):
    """Evaluate a JS expression against live_core.js under node; return parsed JSON."""
    code = f"const c = require({json.dumps(str(CORE))}); console.log(JSON.stringify({expr}));"
    out = subprocess.run([NODE, "-e", code], capture_output=True, text=True, timeout=20)
    assert out.returncode == 0, out.stderr
    return json.loads(out.stdout.strip())


def test_states_and_styles():
    states = js("c.STATES")
    assert states == ["idle", "listening", "thinking", "executing", "speaking", "muted", "error", "reconnecting"]
    styles = js("c.STATE_STYLE")
    colors = set()
    for s in states:
        st = styles[s]
        assert re.fullmatch(r"#[0-9a-fA-F]{6}", st["color"])
        assert st["speed"] > 0 and st["pulse"] >= 0
        colors.add(st["color"].lower())
    assert len(colors) == 8


def test_merge_caption_builds_sentences_per_speaker():
    lines = js("""(() => { let L = [];
        for (const w of ["I'm doing", " well", ",", "thank", "you", "!", "How can", "I help", "you today", "?"])
            L = c.mergeCaption(L, "seven", w);
        return L; })()""")
    assert lines == [{"who": "seven", "text": "I'm doing well, thank you! How can I help you today?", "open": True}]


def test_merge_caption_switches_speaker_and_respects_turns():
    lines = js("""(() => { let L = [];
        L = c.mergeCaption(L, "you", "How are");
        L = c.mergeCaption(L, "you", "you?");
        L = c.mergeCaption(L, "seven", "Fine.");
        L = c.endTurn(L);
        L = c.mergeCaption(L, "seven", "Anything else?");
        L = c.mergeCaption(L, "you", "   ");
        return L; })()""")
    assert [(l["who"], l["text"], l["open"]) for l in lines] == [
        ("you", "How are you?", False),
        ("seven", "Fine.", False),
        ("seven", "Anything else?", True),
    ]


def test_merge_caption_is_pure_and_handles_brackets():
    res = js("""(() => { const L0 = [{who:"you", text:"see", open:true}];
        const L1 = c.mergeCaption(L0, "you", "(this");
        const L2 = c.mergeCaption(L1, "you", ")");
        return {orig: L0, out: L2}; })()""")
    assert res["orig"] == [{"who": "you", "text": "see", "open": True}]
    assert res["out"][0]["text"] == "see (this)"


def test_orb_params_live_and_deterministic():
    quiet = js('c.orbParams("listening", 0, 1.0)')
    loud = js('c.orbParams("listening", 1, 1.0)')
    again = js('c.orbParams("listening", 1, 1.0)')
    unknown = js('c.orbParams("no_such_state", 0.5, 2.0)')
    idle = js('c.orbParams("idle", 0.5, 2.0)')
    assert loud == again
    assert loud["radius"] > quiet["radius"] > 0
    assert loud["particles"] >= 60 and quiet["particles"] >= 60
    assert unknown["color"] == idle["color"]
    speaking = js('c.orbParams("speaking", 0.5, 2.0)')
    assert speaking["color"] != idle["color"]


