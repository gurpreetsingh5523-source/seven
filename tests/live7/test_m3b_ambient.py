def test_launcher_and_launchagent_template():
    sh = ROOT / "scripts" / "seven_app.sh"
    assert sh.exists() and os.access(sh, os.X_OK)
    body = sh.read_text()
    assert "--app=http://127.0.0.1:7879" in body
    assert "--autoplay-policy=no-user-gesture-required" in body
    assert "live7" in body and "Safari" in body
    pl = plistlib.loads((ROOT / "docs" / "com.seven.live.plist").read_bytes())
    assert pl["Label"] == "com.seven.live"
    args = pl["ProgramArguments"]
    assert "-m" in args and "live7" in args
    assert pl.get("RunAtLoad") is True and pl.get("KeepAlive") in (True, {"SuccessfulExit": False})
    assert ".seven" in pl.get("StandardOutPath", "") and ".seven" in pl.get("StandardErrorPath", "")
