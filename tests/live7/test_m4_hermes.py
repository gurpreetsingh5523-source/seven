class FakeSession:
    def __init__(self):
        self.client_content = []

    async def send_client_content(self, turns=None, turn_complete=None):
        self.client_content.append((turns, turn_complete))


def test_finished_job_is_spoken_proactively(tmp_path):
    s = FakeSession()
    events = []

    async def send(e):
        events.append(e)

    async def go():
        relay = LiveRelay(s, None, send)
        b = HermesBridge(tmp_path, runner=fake_runner(reply="The answer is 391. " + "x" * 3000, delay=0.1),
                         on_done=relay.announce_hermes)
        res = await b.ask("What is 17*23?")
        await b.wait_idle()
        return res

    res = asyncio.run(go())
    assert len(s.client_content) == 1
    turns, complete = s.client_content[0]
    assert complete is True
    content = turns[0] if isinstance(turns, list) else turns
    text = content.parts[0].text
    assert content.role == "user"
    assert text.startswith("[Hermes finished]") and "391" in text
    assert len(text) <= 1500 + 200
    # M12 adds "summary"; exactly one hermes_done per job (two = double chime on the page).
    done = [e for e in events if e.get("type") == "hermes_done"]
    assert len(done) == 1 and done[0]["job_id"] == res["job_id"] and done[0]["status"] == "done"
