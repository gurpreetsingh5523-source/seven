def fake_runner(reply="391", code=0, delay=0.2, calls=None):
    async def runner(argv, timeout_s):
        if calls is not None:
            calls.append((list(argv), timeout_s))
        await asyncio.sleep(delay)
        return code, f"{reply}\n\nsession_id: 20261005_x\n", ""
    return runner


def test_ask_returns_fast_and_uses_guarded_cli(tmp_path):
    calls, done = [], []

    async def on_done(job):
        done.append(job)

    async def go():
        b = HermesBridge(tmp_path, runner=fake_runner(delay=1.5, calls=calls), hermes_bin="/x/hermes",
                         on_done=on_done)
        t0 = time.monotonic()
        res = await b.ask("What is 17*23?")
        elapsed = time.monotonic() - t0
        running = json.loads((tmp_path / f"{res['job_id']}.json").read_text())
        await b.wait_idle()
        final = json.loads((tmp_path / f"{res['job_id']}.json").read_text())
        return res, elapsed, running, final

    res, elapsed, running, final = asyncio.run(go())
    assert res["ok"] is True and res["status"] == "started" and res["job_id"]
    assert elapsed < 1.0
    assert calls[0][0] == ["/x/hermes", "chat", "-q", "What is 17*23?", "-Q"]
    for bad in ("-z", "--oneshot", "--yolo"):
        assert bad not in calls[0][0]
    assert running["status"] == "running"
    assert final["status"] == "done" and final["reply"] == "391"
    assert len(done) == 1 and done[0]["reply"] == "391"


def test_error_timeout_and_empty_task(tmp_path):
    async def slow(argv, timeout_s):
        raise asyncio.TimeoutError()

    async def go():
        b1 = HermesBridge(tmp_path / "a", runner=fake_runner(code=1, reply="boom"))
        r1 = await b1.ask("fail please")
        await b1.wait_idle()
        b2 = HermesBridge(tmp_path / "b", runner=slow, timeout_s=1)
        r2 = await b2.ask("take forever")
        await b2.wait_idle()
        r3 = await b1.ask("   ")
        return (json.loads((tmp_path / "a" / f"{r1['job_id']}.json").read_text()),
                json.loads((tmp_path / "b" / f"{r2['job_id']}.json").read_text()), r3)

    j1, j2, r3 = asyncio.run(go())
    assert j1["status"] == "error"
    assert j2["status"] == "timeout"
    assert r3["ok"] is False


def test_result_lists_newest_first(tmp_path):
    async def go():
        b = HermesBridge(tmp_path, runner=fake_runner(delay=0))
        empty = b.result()
        a = await b.ask("first")
        await b.wait_idle()
        await asyncio.sleep(0.01)
        c = await b.ask("second")
        await b.wait_idle()
        return empty, b.result(2), a, c

    empty, res, a, c = asyncio.run(go())
    assert empty == {"ok": True, "jobs": []}
    assert [j["task"] for j in res["jobs"]] == ["second", "first"]


def test_tools_registered_low_risk_with_params(tmp_path):
    assert "task" in TOOL_HINTS["ask_hermes"] and "count" in TOOL_HINTS["hermes_result"]
