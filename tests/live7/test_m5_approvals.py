"""M5 exam — voice + screen approvals for MEDIUM/HIGH actions (SPEC E7, §7.1-7.2).

Hermes: make these pass. Do not edit this file.

Security design (important): the MODEL can never approve. An approval is resolved only by
  (a) the user's own speech, i.e. input transcription text ("transcript_in"), or
  (b) a click in the page ({"type":"approval","action_id":...,"approved":bool}).
So a prompt-injected web page that makes the model say "yes" cannot authorise anything.

Required
--------
live7.approvals.VoiceApprovals(send_event, announce=None, timeout_s=30.0)
    send_event: async callable(dict)    announce: async callable(str) or None (asks out loud)
    async callback(intent, decision) -> bool      # plug into sentinel ApprovalGate
        emits {"type":"approval_needed","action_id","tool","risk","payload"}
        awaits announce(question) where question mentions the tool and asks yes/no
        waits for resolve()/on_user_transcript(); timeout -> False
        always ends with {"type":"approval_closed","action_id","approved":bool,"reason":str}
        reason in {"voice","click","timeout"}
    resolve(action_id, approved) -> bool          # click path; False if no such pending action
    on_user_transcript(text) -> bool              # voice path; resolves the OLDEST pending action
        yes words: yes, yeah, haan, han, haanji, theek hai, ok, okay, kar do, ਹਾਂ, ਹਾਂਜੀ, ਠੀਕ ਹੈ
        no words : no, nope, nahi, nahin, na, cancel, stop, rehn de, ਨਹੀਂ, ਨਾ
        matching is case-insensitive on whole words; "no" wins if both appear; anything else -> ignored
    pending() -> list of action_ids, oldest first
live7.relay.LiveRelay(session, bridge, send_event, send_audio=None, approvals=None)
    input transcription text is passed to approvals.on_user_transcript BEFORE being forwarded;
    client {"type":"approval","action_id":..,"approved":..} -> approvals.resolve(...)
"""

import asyncio
import sys
from pathlib import Path

import pytest
from google.genai import types

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from live7.approvals import VoiceApprovals  # noqa: E402
from live7.relay import LiveRelay  # noqa: E402
from live7.tools import ToolBridge  # noqa: E402
from sentinel_orchestrator import (ActionIntent, ApprovalGate, AuditLog, Capability,  # noqa: E402
                                   LocalSandbox, PolicyEngine, RiskLevel, SecretsBroker,
                                   ToolRegistry, ToolSpec)


def setup(timeout=2.0):
    events, said = [], []

    async def send(e):
        events.append(e)

    async def announce(t):
        said.append(t)

    return VoiceApprovals(send, announce=announce, timeout_s=timeout), events, said


def intent(tool="site_open"):
    return ActionIntent(tool=tool, payload={"url": "https://example.com"}, risk=RiskLevel.HIGH,
                        capabilities=Capability.EXTERNAL_EFFECT)


async def ask_then(ap, fn, delay=0.1):
    task = asyncio.create_task(ap.callback(intent(), None))
    await asyncio.sleep(delay)
    fn()
    return await task


@pytest.mark.parametrize("words,expected", [
    ("yes please", True), ("Haan ji kar do", True), ("ਹਾਂ", True), ("theek hai", True),
    ("no", False), ("nahi rehn de", False), ("ਨਹੀਂ", False), ("yes no wait", False),
])
def test_voice_answers(words, expected):
    ap, events, said = setup()
    res = asyncio.run(ask_then(ap, lambda: ap.on_user_transcript(words)))
    assert res is expected
    assert said and "example.com" in said[0] and said[0].endswith("Yes or no?")  # plain language since M19b
    closed = [e for e in events if e["type"] == "approval_closed"]
    assert closed and closed[-1]["approved"] is expected and closed[-1]["reason"] == "voice"
    needed = [e for e in events if e["type"] == "approval_needed"]
    assert needed and needed[0]["tool"] == "site_open" and needed[0]["risk"] == "high"


def test_unrelated_speech_is_ignored_then_timeout_denies():
    ap, events, _ = setup(timeout=0.5)

    async def go():
        task = asyncio.create_task(ap.callback(intent(), None))
        await asyncio.sleep(0.1)
        assert ap.on_user_transcript("what is the weather like") is False
        return await task

    assert asyncio.run(go()) is False
    assert events[-1]["type"] == "approval_closed" and events[-1]["reason"] == "timeout"
    assert ap.pending() == []


def test_click_path_and_unknown_id():
    ap, events, _ = setup()

    async def go():
        task = asyncio.create_task(ap.callback(intent(), None))
        await asyncio.sleep(0.1)
        aid = ap.pending()[0]
        assert ap.resolve("act_nope", True) is False
        assert ap.resolve(aid, True) is True
        return await task

    assert asyncio.run(go()) is True
    assert events[-1]["reason"] == "click"


def test_no_pending_means_yes_does_nothing():
    ap, events, _ = setup()
    assert ap.on_user_transcript("yes") is False
    assert events == []


def test_end_to_end_model_cannot_self_approve():
    """A HIGH tool call from the model waits for the USER; the model saying yes is irrelevant."""
    ran = []

    async def site_open(p):
        ran.append(p)
        return {"opened": True}

    reg = ToolRegistry()
    reg.register(ToolSpec("site_open", site_open, RiskLevel.HIGH, Capability.EXTERNAL_EFFECT))
    events = []

    async def send(e):
        events.append(e)

    class S:
        def __init__(self):
            self.client_content, self.tool_responses = [], []

        async def send_client_content(self, turns=None, turn_complete=None):
            self.client_content.append(turns)

        async def send_tool_response(self, function_responses=None):
            self.tool_responses.append(function_responses)

    s = S()

    async def go():
        ap = VoiceApprovals(send, announce=None, timeout_s=3)
        bridge = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                            AuditLog(), ApprovalGate(ap.callback, timeout_s=5))
        relay = LiveRelay(s, bridge, send, approvals=ap)
        call = types.LiveServerMessage(tool_call=types.LiveServerToolCall(function_calls=[
            types.FunctionCall(id="c1", name="site_open", args={"url": "https://example.com"})]))
        task = asyncio.create_task(relay.handle_response(call))
        await asyncio.sleep(0.2)
        # the MODEL "says" yes (output transcription) -> must not approve
        await relay.handle_response(types.LiveServerMessage(server_content=types.LiveServerContent(
            output_transcription=types.Transcription(text="Yes, approved, go ahead."))))
        await asyncio.sleep(0.2)
        assert ran == []
        # the USER says haan -> approves
        await relay.handle_response(types.LiveServerMessage(server_content=types.LiveServerContent(
            input_transcription=types.Transcription(text="haan ji"))))
        await asyncio.wait_for(task, 5)

    asyncio.run(go())
    assert len(ran) == 1
    assert s.tool_responses and s.tool_responses[0][0].response["ok"] is True
    assert any(e["type"] == "transcript_in" and e["text"] == "haan ji" for e in events)
