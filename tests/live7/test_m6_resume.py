def test_relay_tracks_resume_handle_and_go_away():
    async def send(e):
        pass

    relay = LiveRelay(None, None, send)
    assert relay.resume_handle is None and relay.go_away is False

    async def go():
        await relay.handle_response(types.LiveServerMessage(
            session_resumption_update=types.LiveServerSessionResumptionUpdate(new_handle="h1", resumable=True)))
        await relay.handle_response(types.LiveServerMessage(
            session_resumption_update=types.LiveServerSessionResumptionUpdate(new_handle="h2", resumable=False)))
        await relay.handle_response(types.LiveServerMessage(go_away=types.LiveServerGoAway(time_left="5s")))

