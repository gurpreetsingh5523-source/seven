"""M7 exam — offline mode: no internet, same page, same relay (SPEC E8, §5 offline.py).

Hermes: make these pass. Do not edit this file.

Design: an OfflineSession that looks EXACTLY like a Gemini Live session to LiveRelay/server
(send_realtime_input / send_client_content / send_tool_response / receive()), so nothing else
changes. Inside it: energy-based end-of-speech -> local STT -> local brain -> local TTS.

Required
--------
live7.offline.OfflineSession(stt, brain, tts, silence_ms=700, threshold=500)
    stt:   callable(pcm16_bytes_16k, lang) -> str            (sync; run it in a thread)
    brain: async callable(text, history: list[dict]) -> str   (history = [{"role","text"}...])
    tts:   async callable(text) -> bytes PCM16 mono 24 kHz   (may return b"" = text-only reply)
    lang:  attribute, default "en"; set_lang(lang) changes it ("pa" or "en")
    async send_realtime_input(audio=Blob | audio_stream_end=True)
        buffers 16 kHz PCM16; a turn ends after `silence_ms` of frames whose RMS < threshold
        that FOLLOW speech (RMS >= threshold), or on audio_stream_end. Pure silence never makes a turn.
    async send_client_content(turns=..., turn_complete=True)    text turn (skips STT)
    async send_tool_response(function_responses=...)            accepted and ignored
    async receive(): yields google.genai.types.LiveServerMessage objects, per turn, in order:
        input_transcription(text)   [voice turns only]
        output_transcription(reply)
        model_turn with inline_data audio/pcm;rate=24000  [only if tts returned bytes]
        turn_complete=True
      and, like the SDK, the iterator ENDS after each turn_complete.
    history grows by user + model entries each turn (last 20 kept).
live7.offline.offline_session_factory(stt, brain, tts) -> callable(**kw) returning an async
    context manager yielding a fresh OfflineSession (ignores voice/resume_handle kwargs).
live7.server.start_server(..., offline_factory=None)
    if the online session_factory fails to CONNECT (raises entering the context) and an
    offline_factory is given, use it immediately and send {"type":"mode","mode":"offline"};
    an online session sends {"type":"mode","mode":"online"} once connected.
    Env SEVEN_MODE=offline forces offline from the start.
live7.__main__: real offline factory = stt7.LocalSTT (add LocalSTT.transcribe_pcm(pcm16_bytes, lang)
    that skips ffmpeg), brain = agent7.LocalOpenAICompatProvider on SEVEN_OFFLINE_BRAIN_URL
    (default http://127.0.0.1:8097, model from SEVEN_OFFLINE_BRAIN_MODEL),
    tts = macOS `say` -> ffmpeg -> 24 kHz PCM16 for English, b"" for Gurmukhi (text-only, honest).
"""

import asyncio
import contextlib
import json
import math
import struct
import sys
from pathlib import Path

import pytest
from google.genai import types

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from live7.offline import OfflineSession, offline_session_factory  # noqa: E402
from live7.server import start_server  # noqa: E402
from live7.tools import ToolBridge  # noqa: E402
from sentinel_orchestrator import (ApprovalGate, AuditLog, LocalSandbox, PolicyEngine,  # noqa: E402
                                   SecretsBroker, ToolRegistry)


def tone(ms, amp=8000, rate=16000):
    n = int(rate * ms / 1000)
    return b"".join(struct.pack("<h", int(amp * math.sin(2 * math.pi * 220 * i / rate))) for i in range(n))


def silence(ms, rate=16000):
    return b"\0\0" * int(rate * ms / 1000)


def fakes(reply="Hello from offline 7.", tts_bytes=b"\x07\x00" * 2400):
    seen = {"stt": [], "brain": []}

    def stt(pcm, lang):
        seen["stt"].append((len(pcm), lang))
        return "what time is it"

    async def brain(text, history):
        seen["brain"].append((text, [dict(h) for h in history]))
        return reply

    async def tts(text):
        return tts_bytes

    return stt, brain, tts, seen


async def feed(sess, pcm, frame_ms=100):
    step = int(16000 * frame_ms / 1000) * 2
    for i in range(0, len(pcm), step):
        await sess.send_realtime_input(audio=types.Blob(data=pcm[i:i + step], mime_type="audio/pcm;rate=16000"))


async def one_turn(sess, timeout=5):
    out = []

    async def go():
        async for m in sess.receive():
            out.append(m)
    await asyncio.wait_for(go(), timeout)
    return out


def test_voice_turn_produces_transcripts_audio_and_ends_iterator():
    stt, brain, tts, seen = fakes()

    async def go():
        s = OfflineSession(stt, brain, tts, silence_ms=700)
        await feed(s, tone(600) + silence(900))
        return await one_turn(s), s

    msgs, s = asyncio.run(go())
    sc = [m.server_content for m in msgs]
    assert sc[0].input_transcription.text == "what time is it"
    assert sc[1].output_transcription.text == "Hello from offline 7."
    assert msgs[2].data == b"\x07\x00" * 2400
    assert sc[-1].turn_complete is True
    assert seen["stt"] and seen["stt"][0][1] == "en" and seen["stt"][0][0] > 0


def test_pure_silence_never_makes_a_turn():
    stt, brain, tts, seen = fakes()

    async def go():
        s = OfflineSession(stt, brain, tts, silence_ms=300)
        await feed(s, silence(2000))
        with pytest.raises(asyncio.TimeoutError):
            await one_turn(s, timeout=0.8)

    asyncio.run(go())
    assert seen["stt"] == [] and seen["brain"] == []


def test_stream_end_closes_turn_and_text_turns_skip_stt():
    stt, brain, tts, seen = fakes(tts_bytes=b"")

    async def go():
        s = OfflineSession(stt, brain, tts, silence_ms=5000)
        await feed(s, tone(400))
        await s.send_realtime_input(audio_stream_end=True)
        m1 = await one_turn(s)
        await s.send_client_content(turns=[types.Content(role="user", parts=[types.Part(text="ਸਤ ਸ੍ਰੀ ਅਕਾਲ")])],
                                    turn_complete=True)
        m2 = await one_turn(s)
        return m1, m2

    m1, m2 = asyncio.run(go())
    assert m1[-1].server_content.turn_complete
    assert all(m.data is None for m in m2)                     # tts returned b"" -> text only
    assert m2[0].server_content.output_transcription.text == "Hello from offline 7."
    assert seen["brain"][1][0] == "ਸਤ ਸ੍ਰੀ ਅਕਾਲ"
    assert len(seen["stt"]) == 1                              # text turn skipped STT
    hist = seen["brain"][1][1]
    assert hist[0] == {"role": "user", "text": "what time is it"} and hist[1]["role"] == "model"


def test_lang_switch_passed_to_stt():
    stt, brain, tts, seen = fakes()

    async def go():
        s = OfflineSession(stt, brain, tts, silence_ms=300)
        s.set_lang("pa")
        await feed(s, tone(400) + silence(500))
        await one_turn(s)

    asyncio.run(go())
    assert seen["stt"][0][1] == "pa"


def test_server_falls_back_to_offline_when_online_cannot_connect(monkeypatch):
    from websockets.asyncio.client import connect
    monkeypatch.setenv("SEVEN_BACKOFF_SCALE", "0.01")
    monkeypatch.delenv("SEVEN_MODE", raising=False)
    stt, brain, tts, seen = fakes()

    def online(**kw):
        @contextlib.asynccontextmanager
        async def cm():
            raise ConnectionError("no internet")
            yield  # pragma: no cover
        return cm()

    async def no(i, d):
        return False

    bridge = ToolBridge(ToolRegistry(), PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                        AuditLog(), ApprovalGate(no, timeout_s=1))

    async def go():
        server = await start_server(online, bridge, port=0,
                                    offline_factory=offline_session_factory(stt, brain, tts))
        base = f"http://127.0.0.1:{server.port}"
        try:
            async with connect(f"ws://127.0.0.1:{server.port}/live", origin=base, max_size=None) as ws:
                pcm = tone(500) + silence(1200)
                for i in range(0, len(pcm), 3200):
                    await ws.send(pcm[i:i + 3200])
                got, audio = [], 0
                for _ in range(40):
                    try:
                        m = await asyncio.wait_for(ws.recv(), 0.5)
                    except asyncio.TimeoutError:
                        continue
                    if isinstance(m, bytes):
                        audio += len(m)
                    else:
                        got.append(json.loads(m))
                    if audio and any(e.get("type") == "transcript_out" for e in got):
                        break
                return got, audio
        finally:
            await server.close()

    got, audio = asyncio.run(go())
    assert {"type": "mode", "mode": "offline"} in got
    assert {"type": "transcript_in", "text": "what time is it"} in got
    assert {"type": "transcript_out", "text": "Hello from offline 7."} in got
    assert audio > 0
