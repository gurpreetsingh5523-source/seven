def test_every_tool_has_a_hint_and_valid_declaration(built):
    reg, _ = built
    missing = sorted(n for n in reg._tools if n not in TOOL_HINTS)
    assert missing == [], f"TOOL_HINTS missing: {missing}"

    async def no(i, d):
        return False

    tb = ToolBridge(reg, PolicyEngine(), LocalSandbox(SecretsBroker(), simulated_latency_s=0),
                    AuditLog(), ApprovalGate(no, timeout_s=1))
    for d in tb.declarations():
        assert d["description"]
        for prop in d["parameters"].get("properties", {}).values():
            assert prop.get("type") in ("STRING", "NUMBER", "INTEGER", "BOOLEAN", "OBJECT", "ARRAY")
    # Gemini closes the session (1007) on an ARRAY without items or an OBJECT without
    # properties — found live 2026-10-06 with browser_task.steps.
    def walk(schema, path):
        t = schema.get("type")
        if t == "ARRAY":
            assert "items" in schema, f"{path}: ARRAY without items"
            walk(schema["items"], path + "[]")
        if t == "OBJECT":
            assert schema.get("properties"), f"{path}: OBJECT without properties"
            for k, v in schema["properties"].items():
                walk(v, f"{path}.{k}")
    for d in tb.declarations():
        for k, v in d["parameters"].get("properties", {}).items():
            walk(v, f"{d['name']}.{k}")
    decl = {d["name"]: d for d in tb.declarations()}
    assert {"from_city", "to_city"} <= set(decl["globe_distance"]["parameters"]["properties"])
    assert "city" in decl["weather_report"]["parameters"]["properties"]


