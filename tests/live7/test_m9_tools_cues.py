NODE = shutil.which("node")


@pytest.mark.skipif(NODE is None, reason="node not installed")
def test_cue_mapping():
    core = ROOT / "static" / "live_core.js"

    def js(expr):
        code = f"const c=require({json.dumps(str(core))});console.log(JSON.stringify({expr}));"
        out = subprocess.run([NODE, "-e", code], capture_output=True, text=True, timeout=20)
        assert out.returncode == 0, out.stderr
        return json.loads(out.stdout)

    assert js("c.CUES") == ["listen", "whoosh", "chirp", "chime", "attention", "stop", "error"]
    cases = {
        '{"type":"tool_started","name":"x"}': "whoosh",
        '{"type":"tool_result","result":{"ok":true}}': "chirp",
        '{"type":"tool_result","result":{"ok":false}}': "error",
        '{"type":"hermes_done","job_id":"j","status":"done"}': "chime",
        '{"type":"approval_needed","action_id":"a"}': "attention",
        '{"type":"state","state":"muted"}': "stop",
        '{"type":"error","error":"x"}': "error",
        '{"type":"state","state":"speaking"}': None,
        '{"type":"transcript_out","text":"hi"}': None,
    }
    for ev, want in cases.items():
        assert js(f"c.cueFor({ev})") == want, ev


